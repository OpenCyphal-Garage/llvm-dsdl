std::string pyConstValue(const TypeExprAST& type, const Value& value)
{
    return renderConstantLiteral(ConstantLiteralLanguage::Python, value, makeConstantTypeInfo(type));
}

/// @brief Collision-free attribute names for one section's fields.
///
/// snake_casing is many-to-one, so `fooBar` and `foo_bar` both fold to `foo_bar`; without this the
/// dataclass would silently declare one attribute for two DSDL fields and the (de)serializer would
/// read/write the wrong one with no error. Built from `section.fields` order so every site agrees.
NamingScope makePyFieldIdents(const SemanticSection& section)
{
    std::vector<std::string> names;
    for (const auto& field : section.fields)
    {
        if (!field.isPadding)
        {
            names.push_back(field.name);
        }
    }
    // The generated methods a field attribute must not shadow are claimed by the FieldName role's
    // policy, so the scope only has to keep the fields apart from each other.
    return makeSectionFieldScope(CodegenNamingLanguage::Python, section);
}

SourceWriter makePyWriter(std::ostringstream& out)
{
    return SourceWriter{out, IndentPolicy::spaces(4)};
}

std::string generatedCommentLine(llvm::StringRef detail)
{
    return "# Generated by llvmdsdl " + std::string(llvmdsdl::kVersionString) + " (" + detail.str() + ").";
}

void emitAttachedDocPy(SourceWriter& w, const AttachedDoc& doc)
{
    for (const auto& line : doc.lines)
    {
        w.line("# " + line.text);
    }
}

std::string runtimeSerializeFn(const std::string& typeName)
{
    // Not a role: typeName is already a projected identifier, so this is a defensive escape of a
    // symbol this generator assembled, not a DSDL name being named.
    return "_serialize_" + codegenSanitizeIdentifier(CodegenNamingLanguage::Python, typeName);
}

std::string runtimeDeserializeFn(const std::string& typeName)
{
    return "_deserialize_" + codegenSanitizeIdentifier(CodegenNamingLanguage::Python, typeName);
}

std::string joinDotted(const std::vector<std::string>& parts)
{
    std::string out;
    for (const auto& p : parts)
    {
        if (!out.empty())
        {
            out += ".";
        }
        out += p;
    }
    return out;
}

std::vector<std::string> splitPackageName(const std::string& packageName)
{
    std::vector<std::string> out;
    std::string              current;
    for (char const c : packageName)
    {
        if (c == '.')
        {
            if (!current.empty())
            {
                out.push_back(
                    codegenProjectIdentifier(CodegenNamingLanguage::Python, IdentifierRole::NamespaceName, current));
                current.clear();
            }
            continue;
        }
        current.push_back(c);
    }
    if (!current.empty())
    {
        out.push_back(codegenProjectIdentifier(CodegenNamingLanguage::Python, IdentifierRole::NamespaceName, current));
    }
    if (out.empty())
    {
        out.emplace_back("dsdl_gen");
    }
    return out;
}

/// @brief Python spelling of the helper body shapes (see HelperBodyPlan.h).
///
/// The suites here get their depth from the writer like any other Python this
/// backend emits. The shared renderer used to bake four spaces into the strings
/// themselves, because indentation is semantic in Python and there was nowhere else
/// to put it.
class PyHelperBodySpelling final : public HelperBodySpelling
{
public:
    explicit PyHelperBodySpelling(SourceWriter& w)
        : w_(w)
    {
    }

    void spellIdentity(const HelperBody& body) override
    {
        open(body);
        w_.line(isFloat(body.signature) ? "return float(value)" : "return int(value)");
        w_.dedent();
    }

    void spellMask(const HelperBody& body) override
    {
        open(body);
        w_.line("return int(value) & " + mask(body.bits));
        w_.dedent();
    }

    void spellSaturateUnsigned(const HelperBody& body) override
    {
        open(body);
        w_.line("raw = int(value)");
        w_.open("if raw < 0:");
        w_.line("return 0");
        w_.dedent();
        w_.open("if raw > " + mask(body.bits) + ":");
        w_.line("return " + mask(body.bits));
        w_.dedent();
        w_.line("return raw");
        w_.dedent();
    }

    void spellSaturateSigned(const HelperBody& body) override
    {
        const auto lo = std::to_string(body.minValue);
        const auto hi = std::to_string(body.maxValue);
        open(body);
        w_.line("raw = int(value)");
        w_.open("if raw < " + lo + ":");
        w_.line("return " + lo);
        w_.dedent();
        w_.open("if raw > " + hi + ":");
        w_.line("return " + hi);
        w_.dedent();
        w_.line("return raw");
        w_.dedent();
    }

    void spellSignExtend(const HelperBody& body) override
    {
        const auto bitMask = mask(body.bits);
        const auto signBit = std::to_string(std::uint64_t{1} << (body.bits - 1U));
        open(body);
        w_.line("raw = int(value) & " + bitMask);
        w_.open("if (raw & " + signBit + ") != 0:");
        w_.line("return raw | (~" + bitMask + ")");
        w_.dedent();
        w_.line("return raw");
        w_.dedent();
    }

    void spellStatusGuard(const HelperBody& body) override
    {
        open(body);
        switch (body.guard)
        {
        case HelperGuardKind::CapacityTooSmall:
            w_.line("return " + std::to_string(body.requiredBits) + " <= capacity_bits");
            break;
        case HelperGuardKind::ArrayLengthOutOfRange:
            w_.line("return (value >= 0) and (value <= " + std::to_string(body.capacity) + ")");
            break;
        case HelperGuardKind::DelimiterOutOfRange:
            w_.line("return (payload_bytes >= 0) and (payload_bytes <= remaining_bytes)");
            break;
        }
        w_.dedent();
    }

    void spellTagMembership(const HelperBody& body) override
    {
        open(body);
        if (body.allowedTags.empty())
        {
            w_.line("return False");
            w_.dedent();
            return;
        }
        std::string condition;
        for (const auto tag : body.allowedTags)
        {
            if (!condition.empty())
            {
                condition += " or ";
            }
            condition += "(tag_value == " + std::to_string(tag) + ")";
        }
        w_.line("return " + condition);
        w_.dedent();
    }

private:
    static bool isFloat(const HelperSignature signature)
    {
        return signature == HelperSignature::Float32 || signature == HelperSignature::Float64;
    }

    static std::string mask(const std::uint32_t bits)
    {
        return renderMaskLiteral(HelperSpellingLanguage::Python, bits);
    }

    /// @brief Names the parameter after what the helper asks about.
    static std::string statusParamName(const HelperBody& body)
    {
        if (body.kind == HelperBodyKind::TagMembership)
        {
            return "tag_value";
        }
        return body.guard == HelperGuardKind::CapacityTooSmall ? "capacity_bits" : "value";
    }

    static std::string signature(const HelperBody& body)
    {
        switch (body.signature)
        {
        case HelperSignature::UnsignedToUnsigned:
        case HelperSignature::SignedToSigned:
            return "(value: int) -> int";
        case HelperSignature::Float32:
        case HelperSignature::Float64:
            return "(value: float) -> float";
        case HelperSignature::ValueToStatus:
            return "(" + statusParamName(body) + ": int) -> bool";
        case HelperSignature::PairToStatus:
            return "(payload_bytes: int, remaining_bytes: int) -> bool";
        }
        return "(value: int) -> int";
    }

    /// @brief Emits the `def` line and descends into its suite.
    void open(const HelperBody& body)
    {
        w_.open("def " + body.symbol + signature(body) + ":");
    }

    SourceWriter& w_;
};

class EmitterContext final
{
public:
    EmitterContext(const SemanticModule&    semantic,
                   std::vector<std::string> packageComponents,
                   const TypeNameVersioning typeNameVersioning)
        : packageComponents_(std::move(packageComponents))
        , index_(semantic)
        , typeNameVersioning_(typeNameVersioning)
    {
    }

    /// @brief Attaches an emit-order trace sink (for the emit-order verifier). Null (default) disables tracing at zero
    /// cost.
    void setTraceSink(EmitTraceSink* const sink)
    {
        traceSink_ = sink;
    }

    /// @brief Records one abstract emit op into the attached sink (no-op when unattached).
    ///
    /// Marked `const` so it can be called through the `const EmitterContext&` the render free
    /// functions hold: it mutates the pointee (the sink), not the pointer.
    template <typename PayloadT = std::int64_t>
    void trace(const EmitTraceOp op, const PayloadT payload = -1) const
    {
        emitTrace(traceSink_, op, static_cast<std::int64_t>(payload));
    }

    /// @brief Marks the start of one (type, direction) trace segment (no-op when unattached).
    void traceSection(const std::string& canonicalName, const EmitTraceDirection direction) const
    {
        emitTraceSection(traceSink_, canonicalName, direction);
    }

    const SemanticDefinition* find(const SemanticTypeRef& ref) const
    {
        return index_.find(ref);
    }

    static std::string namespacePath(const DiscoveredDefinition& info)
    {
        return renderNamespaceRelativePath(CodegenNamingLanguage::Python, info.namespaceComponents).generic_string();
    }

    std::string typeName(const DiscoveredDefinition& info) const
    {
        return renderDefinitionTypeName(CodegenNamingLanguage::Python,
                                        info.namespaceComponents,
                                        info.shortName,
                                        info.majorVersion,
                                        info.minorVersion,
                                        typeNameVersioning_);
    }

    std::string typeName(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return typeName(def->info);
        }

        DiscoveredDefinition tmp;
        tmp.shortName    = ref.shortName;
        tmp.majorVersion = ref.majorVersion;
        tmp.minorVersion = ref.minorVersion;
        return typeName(tmp);
    }

    static std::string fileStem(const DiscoveredDefinition& info)
    {
        return renderVersionedFileStem(CodegenNamingLanguage::Python,
                                       info.shortName,
                                       info.majorVersion,
                                       info.minorVersion);
    }

    static std::filesystem::path relativeFilePath(const DiscoveredDefinition& info)
    {
        return renderRelativeTypeFilePath(CodegenNamingLanguage::Python, info, "py");
    }

    std::filesystem::path relativeFilePath(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return relativeFilePath(def->info);
        }

        return renderRelativeTypeFilePath(CodegenNamingLanguage::Python, ref, "py");
    }

    std::string packageName() const
    {
        return joinDotted(packageComponents_);
    }

    std::filesystem::path packageRootPath() const
    {
        std::filesystem::path out;
        for (const auto& c : packageComponents_)
        {
            out /= c;
        }
        return out;
    }

    std::string modulePath(const DiscoveredDefinition& info) const
    {
        const auto rel = relativeFilePath(info);
        return modulePathFromRelPath(rel);
    }

    std::string modulePath(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return modulePath(def->info);
        }
        return modulePathFromRelPath(relativeFilePath(ref));
    }

private:
    std::string modulePathFromRelPath(const std::filesystem::path& relPath) const
    {
        std::vector<std::string> parts = packageComponents_;
        for (const auto& comp : relPath)
        {
            auto part = comp.string();
            if (part.empty() || part == ".")
            {
                continue;
            }
            if (part.ends_with(".py"))
            {
                part.resize(part.size() - 3);
            }
            parts.push_back(part);
        }
        return joinDotted(parts);
    }

    std::vector<std::string> packageComponents_;
    DefinitionIndex          index_;
    TypeNameVersioning       typeNameVersioning_{TypeNameVersioning::Unversioned};
    EmitTraceSink*           traceSink_ = nullptr;
};

std::string pyFieldBaseType(const SemanticFieldType& type, const EmitterContext& ctx)
{
    switch (type.scalarCategory)
    {
    case SemanticScalarCategory::Bool:
        return "bool";
    case SemanticScalarCategory::Byte:
    case SemanticScalarCategory::Utf8:
    case SemanticScalarCategory::UnsignedInt:
    case SemanticScalarCategory::SignedInt:
        return "int";
    case SemanticScalarCategory::Float:
        return "float";
    case SemanticScalarCategory::Void:
        return "int";
    case SemanticScalarCategory::Composite:
        if (type.compositeType)
        {
            return ctx.typeName(*type.compositeType);
        }
        return "object";
    }
    return "object";
}

std::string pyFieldType(const SemanticFieldType& type, const EmitterContext& ctx)
{
    auto base = pyFieldBaseType(type, ctx);
    if (type.arrayKind == ArrayKind::None)
    {
        return base;
    }
    return "list[" + base + "]";
}

std::string pyDefaultExpr(const SemanticFieldType& type, const EmitterContext& ctx)
{
    if (type.arrayKind != ArrayKind::None)
    {
        return "field(default_factory=list)";
    }

    switch (type.scalarCategory)
    {
    case SemanticScalarCategory::Bool:
        return "False";
    case SemanticScalarCategory::Float:
        return "0.0";
    case SemanticScalarCategory::Composite:
        if (type.compositeType)
        {
            return "field(default_factory=" + ctx.typeName(*type.compositeType) + ")";
        }
        return "None";
    case SemanticScalarCategory::Void:
    case SemanticScalarCategory::Byte:
    case SemanticScalarCategory::Utf8:
    case SemanticScalarCategory::UnsignedInt:
    case SemanticScalarCategory::SignedInt:
        return "0";
    }
    return "None";
}

void emitSectionConstants(SourceWriter& w, const std::string& prefix, const SemanticSection& section)
{
    std::vector<std::string> constNames;
    constNames.reserve(section.constants.size());
    for (const auto& constant : section.constants)
    {
        constNames.push_back(constant.name);
    }
    NamingScope const constScope = makeSectionConstantScope(CodegenNamingLanguage::Python, section);
    const auto        prefixupper =
        codegenProjectIdentifier(CodegenNamingLanguage::Python, IdentifierRole::ConstantName, prefix);
    for (const auto& constant : section.constants)
    {
        emitAttachedDocPy(w, constant.doc);
        const auto constName = prefixupper + "_" + constScope.get(IdentifierRole::ConstantName, constant.name);
        w.line(constName + " = " + pyConstValue(constant.type, constant.value));
    }
}

void emitClassMethods(SourceWriter& w, const std::string& typeName)
{
    w.open("def serialize(self) -> bytes:");
    w.line("return " + runtimeSerializeFn(typeName) + "(self)");
    w.dedent();
    w.blank();

    w.line("@classmethod");
    w.open("def deserialize(cls, data: bytes | bytearray | memoryview) -> \"" + typeName + "\":");
    w.line("value, _consumed = " + runtimeDeserializeFn(typeName) + "(bytes(data))");
    w.line("return value");
    w.dedent();
    w.blank();

    w.open("def _serialize_to(self, writer: object) -> None:");
    w.line("writer.write(self.serialize())");
    w.dedent();
    w.blank();

    w.line("@classmethod");
    w.open("def _deserialize_from(cls, reader: object) -> \"" + typeName + "\":");
    w.line("return cls.deserialize(reader.read())");
    w.dedent();
}

void emitStructSectionType(SourceWriter&          w,
                           const std::string&     typeName,
                           const SemanticSection& section,
                           const AttachedDoc&     typeDoc,
                           const EmitterContext&  ctx,
                           const std::string&     fullName,
                           const std::uint32_t    majorVersion,
                           const std::uint32_t    minorVersion)
{
    emitAttachedDocPy(w, docWithDeprecationNotice(typeDoc, section.deprecated, fullName, majorVersion, minorVersion));
    w.line("@dataclass(slots=True)");
    w.open("class " + typeName + ":");

    bool              emittedField = false;
    const NamingScope fieldIdents  = makePyFieldIdents(section);
    for (const auto& field : section.fields)
    {
        if (field.isPadding)
        {
            continue;
        }
        emittedField = true;
        emitAttachedDocPy(w, field.doc);
        const auto fieldName = fieldIdents.get(IdentifierRole::FieldName, field.name);
        w.line(fieldName + ": " + pyFieldType(field.resolvedType, ctx) + " = " +
               pyDefaultExpr(field.resolvedType, ctx));
    }
    if (!emittedField)
    {
        w.line("pass");
    }
    else
    {
        w.blank();
    }
    emitClassMethods(w, typeName);
    w.dedent();
}

void emitUnionSectionType(SourceWriter&          w,
                          const std::string&     typeName,
                          const SemanticSection& section,
                          const AttachedDoc&     typeDoc,
                          const EmitterContext&  ctx,
                          const std::string&     fullName,
                          const std::uint32_t    majorVersion,
                          const std::uint32_t    minorVersion)
{
    emitAttachedDocPy(w, docWithDeprecationNotice(typeDoc, section.deprecated, fullName, majorVersion, minorVersion));
    w.line("@dataclass(slots=True)");
    w.open("class " + typeName + ":");
    w.line("_tag: int = 0");

    const NamingScope fieldIdents = makePyFieldIdents(section);
    for (const auto& field : section.fields)
    {
        if (field.isPadding)
        {
            continue;
        }
        emitAttachedDocPy(w, field.doc);
        const auto fieldName = fieldIdents.get(IdentifierRole::FieldName, field.name);
        w.line(fieldName + ": " + pyFieldType(field.resolvedType, ctx) + " | None = None");
    }

    w.blank();
    emitClassMethods(w, typeName);
    w.dedent();
}

void emitSectionType(SourceWriter&          w,
                     const std::string&     typeName,
                     const SemanticSection& section,
                     const AttachedDoc&     typeDoc,
                     const EmitterContext&  ctx,
                     const std::string&     fullName,
                     const std::uint32_t    majorVersion,
                     const std::uint32_t    minorVersion)
{
    if (section.isUnion)
    {
        emitUnionSectionType(w, typeName, section, typeDoc, ctx, fullName, majorVersion, minorVersion);
    }
    else
    {
        emitStructSectionType(w, typeName, section, typeDoc, ctx, fullName, majorVersion, minorVersion);
    }
}

