    /// @brief A getter's or a setter's signature: a method of the section's `const`, speaking the
    ///        member's own type.
    [[nodiscard]] std::string accessorSignature(mlir::func::FuncOp fn, const std::string& name, const bool getter) const
    {
        const Accessed    a       = accessed(fn);
        const Storage     storage = storageOf(*a.member);
        const bool        indexed = fn.getNumArguments() == (getter ? 3U : 4U);
        const std::string index   = indexed ? ", elementIndex: number" : "";
        const bool        rebind  = (storage == Storage::Number) || (storage == Storage::Boolean);
        if (getter && mlir::isa<mlir::dsdl::PtrType>(fn.getResultTypes().front()))
        {
            // The nested type's buffer, as a subarray, which carries its own length.
            return name + "(buffer: Uint8Array" + index + "): Uint8Array";
        }
        if (getter)
        {
            return name + "(buffer: Uint8Array" + index + "): " + elementTsType(*a.member);
        }
        return name + "(buffer: Uint8Array" + index + ", " + (rebind ? "memberValue: " : "value: ") +
               elementTsType(*a.member) + "): void";
    }

    /// @brief Opens a getter or a setter. The plan holds an integer in a `bigint`: the size is the
    ///        buffer's own length as one, an expression rather than a local; an index, and a
    ///        `number` or a `boolean` member, are rebound at entry and a getter's answer is converted
    ///        at the return.
    std::vector<std::string> openAccessor(SourceWriter& w, mlir::func::FuncOp fn, const bool getter) const
    {
        const Accessed a         = accessed(fn);
        const Storage  storage   = storageOf(*a.member);
        const bool     composite = getter && mlir::isa<mlir::dsdl::PtrType>(fn.getResultTypes().front());
        const bool     indexed   = fn.getNumArguments() == (getter ? 3U : 4U);
        accessor_                = getter ? Accessor::Getter : Accessor::Setter;
        returnCast_.clear();
        if (getter && !composite)
        {
            if (storage == Storage::Number)
            {
                returnCast_ = "Number";
            }
            else if (storage == Storage::Boolean)
            {
                returnCast_ = "boolean";
            }
        }
        std::vector<std::string> parameters{"buffer", file_.global("BigInt") + "(buffer.length)"};
        if (indexed)
        {
            w.line("const index: bigint = " + file_.global("BigInt") + "(elementIndex);");
            parameters.emplace_back("index");
        }
        if (!getter)
        {
            if (storage == Storage::Number)
            {
                w.line("const value: bigint = " + file_.global("BigInt") + "(memberValue);");
            }
            else if (storage == Storage::Boolean)
            {
                w.line("const value: bigint = memberValue ? 1n : 0n;");
            }
            parameters.emplace_back("value");
        }
        return parameters;
    }

    void returnValue(SourceWriter& w, const llvm::StringRef expr) const override
    {
        // A getter answers the value in the member's own type; a setter answers the code alone.
        if (accessor_ == Accessor::Getter)
        {
            if (returnCast_ == "Number")
            {
                w.line("return " + file_.global("Number") + "(" + expr.str() + ");");
            }
            else if (returnCast_ == "boolean")
            {
                w.line("return " + expr.str() + " !== 0n;");
            }
            else
            {
                w.line("return " + expr.str() + ";");
            }
            return;
        }
        // A setter answers nothing, and throws where the code it would answer is an error.
        if (accessor_ == Accessor::Setter)
        {
            raiseOn(w, expr);
            return;
        }
        w.line("return " + expr.str() + ";");
    }

    void returnWithSize(SourceWriter& w, const llvm::StringRef error, const llvm::StringRef used) const override
    {
        // The size used, where the code is no error, which is thrown.
        raiseOn(w, error);
        w.line("return " + used.str() + ";");
    }

    /// @brief Throws the error @p code states, where it states one: a body the lowering found cannot
    ///        fail throws nothing.
    void raiseOn(SourceWriter& w, const llvm::StringRef code) const
    {
        if (cannotFail_)
        {
            return;
        }
        w.open("if (" + code.str() + " !== 0) {");
        w.line("throw new " + file_.global("Error") + "(" + file_.runtime() + ".errorMessage(" + code.str() + "));");
        w.close("}");
    }

