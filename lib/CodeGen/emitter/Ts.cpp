    [[nodiscard]] std::string viewBytes(mlir::dsdl::LoadViewOp op, const ValueNames& names) const override
    {
        return viewTarget(op.getObject(), op.getMember(), op.getIndex(), names);
    }

    [[nodiscard]] std::string viewSize(mlir::dsdl::LoadViewOp op, const ValueNames& names) const override
    {
        return file_.global("BigInt") + "(" + viewTarget(op.getObject(), op.getMember(), op.getIndex(), names) +
               ".length)";
    }

    void storeView(SourceWriter& w, mlir::dsdl::StoreViewOp op, const ValueNames& names) const override
    {
        const std::string bytes = names(op.getBytes());
        w.line(viewTarget(op.getObject(), op.getMember(), op.getIndex(), names) + " = " + bytes + ".subarray(0, " +
               file_.global("Math") + ".min(" + asNumber(op.getSizeBytes(), names) + ", " + bytes + ".length));");
    }

    void clearView(SourceWriter& w, mlir::dsdl::ClearViewOp op, const ValueNames& names) const override
    {
        // A fixed array of views is every element empty; a variable-length one is sized by the plan.
        mlir::dsdl::IOOp io = memberOf(op.getObject(), op.getMember()).io;
        w.line(memberAccess(op.getObject(), op.getMember(), names) + " = " +
               ((io.getArrayKind() == "fixed")
                    ? file_.global("Array") + ".from({ length: " + std::to_string(io.getArrayCapacity()) +
                          " }, () => new " + file_.global("Uint8Array") + "(0))"
                    : "new " + file_.global("Uint8Array") + "(0)") +
               ";");
    }

    void copyBytes(SourceWriter& w, mlir::dsdl::CopyBytesOp op, const ValueNames& names) const override
    {
        // What the view holds, up to the width, then zeros to the width. The plan's capacity check
        // established the width at the destination.
        const std::string destination = names(op.getDestination());
        const std::string source      = names(op.getSource());
        const std::string width       = std::to_string(op.getBytes());
        const std::string copied      = fresh("copied");
        w.line("const " + copied + " = " + file_.global("Math") + ".min(" + asNumber(op.getSourceSizeBytes(), names) +
               ", " + source + ".length, " + width + ");");
        w.line(destination + ".set(" + source + ".subarray(0, " + copied + "), 0);");
        w.line(destination + ".fill(0, " + copied + ", " + width + ");");
    }

    [[nodiscard]] std::string callSerdes(mlir::dsdl::CallSerdesOp /*op*/, const ValueNames& /*names*/) const override
    {
        llvm::report_fatal_error(
            "TypeScript spelling: a nested call reaches TypeScript folded to dsdl.call_serdes_sized");
    }

    void declareCallSerdes(SourceWriter& /*w*/,
                           const llvm::StringRef /*name*/,
                           mlir::dsdl::CallSerdesOp /*op*/,
                           const ValueNames& /*names*/) const override
    {
        llvm::report_fatal_error(
            "TypeScript spelling: a nested call reaches TypeScript folded to dsdl.call_serdes_sized");
    }

    void declareCallSerdesSized(SourceWriter&                 w,
                                const llvm::StringRef         error,
                                const llvm::StringRef         consumed,
                                mlir::dsdl::CallSerdesSizedOp op,
                                const ValueNames&             names) const override
    {
        // The nested value serialises itself into the subarray from the buffer's offset, which ends
        // where the space the plan offers does or the buffer does, and answers what it used or a
        // negative code. What it used means something only where the code is zero, so it holds
        // the answer as it came, and the code is read off it.
        const std::string buffer  = names(op.getBuffer());
        const std::string bounded = op.getAvailable() ? buffer + ".subarray(0, " +
                                                            cast(names(op.getAvailable()),
                                                                 op.getAvailable().getType(),
                                                                 mlir::IndexType::get(op.getContext())) +
                                                            ")"
                                                      : buffer;
        const std::string call    = nestedFunction(op) + "(" + names(op.getObject()) + ", " + bounded + ")";
        if (consumed.empty() && error.empty())
        {
            discard(w, call);
            return;
        }
        if (consumed.empty())
        {
            declare(w, op.getError().getType(), error, file_.global("Math") + ".min(" + call + ", 0)");
            return;
        }
        declare(w, op.getConsumed().getType(), consumed, call);
        if (!error.empty())
        {
            declare(w, op.getError().getType(), error, consumed.str() + " < 0 ? " + consumed.str() + " : 0");
        }
    }

    [[nodiscard]] const WireImageSpelling* wireImages() const override
    {
        return this;
    }

    // A whole wire image, in a `Uint8Array`.

    [[nodiscard]] std::string bytesZeroed(mlir::dsdl::BytesZeroedOp op, const ValueNames& names) const override
    {
        return "new " + file_.global("Uint8Array") + "(" + asNumber(op.getLength(), names) + ")";
    }

