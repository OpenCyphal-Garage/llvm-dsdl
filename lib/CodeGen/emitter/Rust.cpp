    {
        const auto found = helperNames_.find(callee);
        if (found == helperNames_.end())
        {
            llvm::report_fatal_error(llvm::Twine("Rust spelling: a call to a helper this module does "
                                                 "not declare: ") +
                                     callee);
        }
        return found->second;
    }

