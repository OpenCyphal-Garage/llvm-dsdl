std::string headerFileName(const DiscoveredDefinition& info)
{
    return renderDefinitionFileStem(CodegenNamingLanguage::Cpp, info.shortName, info.majorVersion, info.minorVersion) +
           ".hpp";
}

std::string headerGuard(const DiscoveredDefinition& info)
{
    return renderIncludeGuard(CodegenNamingLanguage::Cpp,
                              "LLVMDSDL_CPP_",
                              info.fullName,
                              info.majorVersion,
                              info.minorVersion,
                              "_HPP");
}

std::string valueToCppExpr(const TypeExprAST& type, const Value& value)
{
    return renderConstantLiteral(ConstantLiteralLanguage::Cpp, value, makeConstantTypeInfo(type));
}

std::string unsignedStorageType(const std::uint32_t bitLength)
{
    return renderUnsignedStorageToken(StorageTokenLanguage::Cpp, bitLength);
}

std::string signedStorageType(const std::uint32_t bitLength)
{
    return renderSignedStorageToken(StorageTokenLanguage::Cpp, bitLength);
}

std::string unsignedGetter(const std::uint32_t bitLength)
{
    return "dsdl_runtime_get_u" + std::string(scalarWidthSuffix(bitLength));
}

std::string generatedCommentLine(llvm::StringRef detail)
{
    return llvm::formatv("// Generated by llvmdsdl {0} ({1}).", llvmdsdl::kVersionString, detail).str();
}

void emitAttachedDocCpp(SourceWriter& w, const AttachedDoc& doc)
{
    for (const auto& line : doc.lines)
    {
        w.line(line.text.empty() ? std::string{"//"} : "// " + line.text);
    }
}

std::string cppNamespacePath(const std::vector<std::string>& components)
{
    std::string out;
    for (const auto& component : components)
    {
        if (!out.empty())
        {
            out += "::";
        }
        out += codegenProjectIdentifier(CodegenNamingLanguage::Cpp, IdentifierRole::NamespaceName, component);
    }
    return out;
}

/// @brief C++ spelling of the helper body shapes (see HelperBodyPlan.h).
///
/// Conditional expressions where a body is one `return`, which is how the rest of
/// the generated headers read, and a block only where a body genuinely has several
/// statements.
class CppHelperBodySpelling final : public HelperBodySpelling
{
public:
    explicit CppHelperBodySpelling(SourceWriter& w)
        : w_(w)
    {
    }

    void spellIdentity(const HelperBody& body) override
    {
        oneLiner(body, "return value;");
    }

    void spellMask(const HelperBody& body) override
    {
        oneLiner(body, "return value & " + mask(body.bits) + ";");
    }

    void spellSaturateUnsigned(const HelperBody& body) override
    {
        oneLiner(body, "return (value > " + mask(body.bits) + ") ? " + mask(body.bits) + " : value;");
    }

    void spellSaturateSigned(const HelperBody& body) override
    {
        open(body);
        w_.line("if (value < " + std::to_string(body.minValue) + "LL) { return " + std::to_string(body.minValue) +
                "LL; }");
        w_.line("if (value > " + std::to_string(body.maxValue) + "LL) { return " + std::to_string(body.maxValue) +
                "LL; }");
        w_.line("return value;");
        w_.close("};");
    }

    void spellSignExtend(const HelperBody& body) override
    {
        const auto bitMask = mask(body.bits);
        const auto signBit = std::to_string(std::uint64_t{1} << (body.bits - 1U)) + "ULL";
        open(body);
        w_.line("const std::uint64_t raw = static_cast<std::uint64_t>(value) & " + bitMask + ";");
        w_.open("if ((raw & " + signBit + ") != 0ULL) {");
        w_.line("return static_cast<std::int64_t>(raw | (~" + bitMask + "));");
        w_.close("}");
        w_.line("return static_cast<std::int64_t>(raw);");
        w_.close("};");
    }

    void spellStatusGuard(const HelperBody& body) override
    {
        std::string condition;
        std::string error;
        switch (body.guard)
        {
        case HelperGuardKind::CapacityTooSmall:
            condition = std::to_string(body.requiredBits) + "LL > capacity_bits";
            error     = "DSDL_RUNTIME_ERROR_SERIALIZATION_BUFFER_TOO_SMALL";
            break;
        case HelperGuardKind::ArrayLengthOutOfRange:
            condition = "(value < 0LL) || (value > " + std::to_string(body.capacity) + "LL)";
            error     = "DSDL_RUNTIME_ERROR_REPRESENTATION_BAD_ARRAY_LENGTH";
            break;
        case HelperGuardKind::DelimiterOutOfRange:
            condition = "(payload_bytes < 0LL) || (payload_bytes > remaining_bytes)";
            error     = "DSDL_RUNTIME_ERROR_REPRESENTATION_BAD_DELIMITER_HEADER";
            break;
        }
        oneLiner(body,
                 "return (" + condition + ") ? static_cast<std::int8_t>(-" + error +
                     ") : static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS);");
    }

    void spellTagMembership(const HelperBody& body) override
    {
        const auto badTag = std::string("static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_REPRESENTATION_BAD_UNION_TAG)");
        if (body.allowedTags.empty())
        {
            oneLiner(body, "return " + badTag + ";");
            return;
        }
        std::string condition;
        for (const auto tag : body.allowedTags)
        {
            if (!condition.empty())
            {
                condition += " || ";
            }
            condition += "(tag_value == " + std::to_string(tag) + "LL)";
        }
        oneLiner(body, "return (" + condition + ") ? static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS) : " + badTag + ";");
    }

private:
    static std::string mask(const std::uint32_t bits)
    {
        return renderMaskLiteral(HelperSpellingLanguage::Cpp, bits);
    }

    static std::string floatType(const HelperSignature signature)
    {
        return signature == HelperSignature::Float64 ? "double" : "float";
    }

    /// @brief Names the parameter after what the helper asks about.
    static std::string statusParamName(const HelperBody& body)
    {
        if (body.kind == HelperBodyKind::TagMembership)
        {
            return "tag_value";
        }
        return body.guard == HelperGuardKind::CapacityTooSmall ? "capacity_bits" : "value";
    }

    static std::string signature(const HelperBody& body)
    {
        switch (body.signature)
        {
        case HelperSignature::UnsignedToUnsigned:
            return "[](const std::uint64_t value) -> std::uint64_t";
        case HelperSignature::SignedToSigned:
            return "[](const std::int64_t value) -> std::int64_t";
        case HelperSignature::ValueToStatus:
            return "[](const std::int64_t " + statusParamName(body) + ") -> std::int8_t";
        case HelperSignature::PairToStatus:
            return "[](const std::int64_t payload_bytes, const std::int64_t remaining_bytes) -> std::int8_t";
        case HelperSignature::Float32:
        case HelperSignature::Float64:
            return "[](const " + floatType(body.signature) + " value) -> " + floatType(body.signature);
        }
        return "[](const std::uint64_t value) -> std::uint64_t";
    }

    void oneLiner(const HelperBody& body, const std::string& statement)
    {
        w_.line("const auto " + body.symbol + " = " + signature(body) + " { " + statement + " };");
    }

    void open(const HelperBody& body)
    {
        w_.open("const auto " + body.symbol + " = " + signature(body) + " {");
    }

    SourceWriter& w_;
};

void emitNamespaceOpen(SourceWriter& w, const std::vector<std::string>& components)
{
    if (components.empty())
    {
        return;
    }
    for (const auto& component : components)
    {
        w.line("namespace " +
               codegenProjectIdentifier(CodegenNamingLanguage::Cpp, IdentifierRole::NamespaceName, component) + " {");
    }
    w.blank();
}

void emitNamespaceClose(SourceWriter& w, const std::vector<std::string>& components)
{
    if (components.empty())
    {
        return;
    }
    w.blank();
    for (const auto& component : std::views::reverse(components))
    {
        w.line("} // namespace " +
               codegenProjectIdentifier(CodegenNamingLanguage::Cpp, IdentifierRole::NamespaceName, component));
    }
}

class EmitterContext final
{
public:
    EmitterContext(const SemanticModule&    semantic,
                   const bool               emitDeprecationAttributes,
                   const TypeNameVersioning typeNameVersioning)
        : index_(semantic)
        , typeNameVersioning_(typeNameVersioning)
        , emitDeprecationAttributes_(emitDeprecationAttributes)
    {
    }

    /// @brief Whether generated type names carry the definition's version.
    TypeNameVersioning typeNameVersioning() const
    {
        return typeNameVersioning_;
    }

    /// @brief True when `@deprecated` definitions should carry a language-native attribute.
    bool emitDeprecationAttributes() const
    {
        return emitDeprecationAttributes_;
    }

    /// @brief Attaches an emit-order trace sink (for the emit-order verifier). Null (default) disables tracing at zero
    /// cost.
    void setTraceSink(EmitTraceSink* const sink)
    {
        traceSink_ = sink;
    }

    /// @brief Records one abstract emit op into the attached sink (no-op when unattached).
    template <typename PayloadT = std::int64_t>
    void trace(const EmitTraceOp op, const PayloadT payload = -1) const
    {
        emitTrace(traceSink_, op, static_cast<std::int64_t>(payload));
    }

    /// @brief Marks the start of one (type, direction) trace segment (no-op when unattached).
    void traceSection(const std::string& canonicalName, const EmitTraceDirection direction) const
    {
        emitTraceSection(traceSink_, canonicalName, direction);
    }

    const SemanticDefinition* find(const SemanticTypeRef& ref) const
    {
        return index_.find(ref);
    }

    std::string cppTypeName(const DiscoveredDefinition& info) const
    {
        return renderDefinitionTypeName(CodegenNamingLanguage::Cpp,
                                        info.namespaceComponents,
                                        info.shortName,
                                        info.majorVersion,
                                        info.minorVersion,
                                        typeNameVersioning_);
    }

    std::string cppTypeName(const SemanticDefinition& def) const
    {
        return cppTypeName(def.info);
    }

    std::string cppTypeName(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return cppTypeName(*def);
        }

        // Nothing to count versions against, so assume the name is ambiguous and spell the version.
        // Guessing the other way would name a type that does not exist if it turns out there are two.
        return renderDefinitionTypeName(CodegenNamingLanguage::Cpp,
                                        ref.namespaceComponents,
                                        ref.shortName,
                                        ref.majorVersion,
                                        ref.minorVersion,
                                        typeNameVersioning_);
    }

    std::string cppQualifiedTypeName(const SemanticDefinition& def) const
    {
        std::string out = "::";
        const auto  ns  = cppNamespacePath(def.info.namespaceComponents);
        if (!ns.empty())
        {
            out += ns + "::";
        }
        out += cppTypeName(def);
        return out;
    }

    std::string cppQualifiedTypeName(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return cppQualifiedTypeName(*def);
        }

        std::string out = "::";
        const auto  ns  = cppNamespacePath(ref.namespaceComponents);
        if (!ns.empty())
        {
            out += ns + "::";
        }
        out += cppTypeName(ref);
        return out;
    }

    static std::string relativeHeaderPath(const SemanticDefinition& def)
    {
        std::filesystem::path p;
        for (const auto& ns : def.info.namespaceComponents)
        {
            p /= ns;
        }
        p /= headerFileName(def.info);
        return p.generic_string();
    }

private:
    DefinitionIndex    index_;
    TypeNameVersioning typeNameVersioning_{TypeNameVersioning::Unversioned};
    EmitTraceSink*     traceSink_ = nullptr;
    bool               emitDeprecationAttributes_{false};
};

SourceWriter makeCppWriter(std::ostringstream& out)
{
    return SourceWriter{out, IndentPolicy::spaces(2)};
}

enum class CppFlavor
{
    Std,
    Pmr,
    Autosar,
};

bool isPmrFlavor(const CppFlavor flavor)
{
    return flavor == CppFlavor::Pmr;
}

bool isAutosarFlavor(const CppFlavor flavor)
{
    return flavor == CppFlavor::Autosar;
}

class FunctionBodyEmitter final
{
public:
    explicit FunctionBodyEmitter(const EmitterContext& ctx, const CppFlavor flavor)
        : ctx_(ctx)
        , flavor_(flavor)
    {
    }

    /// @brief Records one abstract emit op via the shared EmitterContext sink (no-op when unattached).
    template <typename PayloadT = std::int64_t>
    void trace(const EmitTraceOp op, const PayloadT payload = -1) const
    {
        ctx_.trace(op, payload);
    }

    void emitSerializeFunction(SourceWriter&                    w,
                               const std::string&               typeName,
                               const SemanticSection&           section,
                               const LoweredSectionFacts* const sectionFacts)
    {
        const NamingScope fieldScope = makeSectionFieldScope(CodegenNamingLanguage::Cpp, section);
        w.line("inline std::int8_t " + typeName + "_serialize_(const " + typeName +
               "* const obj, std::uint8_t* const buffer, std::size_t* const "
               "inout_buffer_size_bytes" +
               (isPmrFlavor(flavor_) ? ", ::llvmdsdl::cpp::MemoryResource* const memory_resource" : "") + ")");
        w.open("{");
        w.open("if ((obj == nullptr) || (buffer == nullptr) || (inout_buffer_size_bytes == nullptr)) {");
        w.line("return static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
        w.close("}");
        if (isPmrFlavor(flavor_))
        {
            w.line("::llvmdsdl::cpp::MemoryResource* const effective_memory_resource = "
                   "(memory_resource != nullptr) ? memory_resource : obj->_memory_resource;");
            w.line("(void)effective_memory_resource;");
        }
        w.line("const std::size_t capacity_bytes = *inout_buffer_size_bytes;");
        w.line("std::size_t offset_bits = 0U;");
        const auto emitted = emitNativeFunctionSkeleton(
            section,
            sectionFacts,
            HelperBindingDirection::Serialize,
            NativeFunctionSkeletonCallbacks{[&w](const SectionHelperBindingPlan& helperBindings) {
                                                emitSerializeMlirHelperBindings(w, helperBindings);
                                            },
                                            [&w](const std::string& missingHelperRequirement) {
                                                w.line("/* missing lowered helper contract: " +
                                                       missingHelperRequirement + " */");
                                                w.line("return static_cast<std::int8_t>("
                                                       "-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
                                            },
                                            [this, &w](const SectionHelperBindingPlan& helperBindings) {
                                                const auto capacityHelper =
                                                    helperBindingName(helperBindings.capacityCheck->symbol);
                                                const auto errCapacity = nextName("err_capacity");
                                                w.line("const std::int8_t " + errCapacity + " = " + capacityHelper +
                                                       "(static_cast<std::int64_t>(capacity_bytes * 8U));");
                                                w.open("if (" + errCapacity +
                                                       " != static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS)) {");
                                                w.line("return " + errCapacity + ";");
                                                w.close("}");
                                            },
                                            [this, &w, &section, sectionFacts, &fieldScope](
                                                const LoweredBodyRenderIR& renderIR) {
                                                NativeEmitterTraversalCallbacks callbacks;
                                                callbacks.onUnionDispatch =
                                                    [this, &w, &section, sectionFacts, &renderIR](
                                                        const std::vector<PlannedFieldStep>& unionBranches) {
                                                        emitSerializeUnion(w,
                                                                           section,
                                                                           unionBranches,
                                                                           "obj",
                                                                           sectionFacts,
                                                                           renderIR.helperBindings);
                                                    };
                                                callbacks.onFieldAlignment = [this,
                                                                              &w](const std::int64_t alignmentBits) {
                                                    emitAlignSerialize(w, alignmentBits);
                                                };
                                                callbacks.onField =
                                                    [this, &w, &fieldScope](const PlannedFieldStep& fieldStep) {
                                                        const auto* const field = fieldStep.field;
                                                        emitSerializeValue(w,
                                                                           field->resolvedType,
                                                                           "obj->" +
                                                                               fieldScope.get(IdentifierRole::FieldName,
                                                                                              field->name),
                                                                           fieldStep.arrayLengthPrefixBits,
                                                                           fieldStep.fieldFacts);
                                                    };
                                                callbacks.onPaddingAlignment = [this,
                                                                                &w](const std::int64_t alignmentBits) {
                                                    emitAlignSerialize(w, alignmentBits);
                                                };
                                                callbacks.onPadding = [this, &w](const PlannedFieldStep& fieldStep) {
                                                    const auto* const field = fieldStep.field;
                                                    emitSerializePadding(w, field->resolvedType);
                                                };
                                                return callbacks;
                                            },
                                            [this, &w]() {
                                                emitAlignSerialize(w, 8);
                                                w.line("*inout_buffer_size_bytes = "
                                                       "static_cast<std::size_t>(offset_bits / 8U);");
                                                w.line("return static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS);");
                                            }});
        if (!emitted)
        {
            w.close("}");
            w.blank();
            return;
        }
        w.close("}");
        w.blank();
    }

    void emitDeserializeFunction(SourceWriter&                    w,
                                 const std::string&               typeName,
                                 const SemanticSection&           section,
                                 const LoweredSectionFacts* const sectionFacts)
    {
        const NamingScope fieldScope = makeSectionFieldScope(CodegenNamingLanguage::Cpp, section);
        w.line("inline std::int8_t " + typeName + "_deserialize_(" + typeName +
               "* const out_obj, const std::uint8_t* buffer, std::size_t* const "
               "inout_buffer_size_bytes" +
               (isPmrFlavor(flavor_) ? ", ::llvmdsdl::cpp::MemoryResource* const memory_resource" : "") + ")");
        w.open("{");
        w.open("if ((out_obj == nullptr) || (inout_buffer_size_bytes == nullptr) || ((buffer == nullptr) && (0U != "
               "*inout_buffer_size_bytes))) {");
        w.line("return static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
        w.close("}");
        if (isPmrFlavor(flavor_))
        {
            w.line("::llvmdsdl::cpp::MemoryResource* const effective_memory_resource = "
                   "(memory_resource != nullptr) ? memory_resource : out_obj->_memory_resource;");
            w.line("(void)effective_memory_resource;");
            w.line("if (effective_memory_resource != nullptr) { "
                   "out_obj->set_memory_resource(effective_memory_resource); }");
        }
        w.open("if (buffer == nullptr) {");
        w.line("buffer = reinterpret_cast<const std::uint8_t*>(\"\");");
        w.close("}");
        w.line("const std::size_t capacity_bytes = *inout_buffer_size_bytes;");
        w.line("const std::size_t capacity_bits = capacity_bytes * 8U;");
        w.line("std::size_t offset_bits = 0U;");
        const auto emitted = emitNativeFunctionSkeleton(
            section,
            sectionFacts,
            HelperBindingDirection::Deserialize,
            NativeFunctionSkeletonCallbacks{[&w](const SectionHelperBindingPlan& helperBindings) {
                                                emitDeserializeMlirHelperBindings(w, helperBindings);
                                            },
                                            [&w](const std::string& missingHelperRequirement) {
                                                w.line("/* missing lowered helper contract: " +
                                                       missingHelperRequirement + " */");
                                                w.line("return static_cast<std::int8_t>("
                                                       "-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
                                            },
                                            nullptr,
                                            [this, &w, &section, sectionFacts, &fieldScope](
                                                const LoweredBodyRenderIR& renderIR) {
                                                NativeEmitterTraversalCallbacks callbacks;
                                                callbacks.onUnionDispatch =
                                                    [this, &w, &section, sectionFacts, &renderIR](
                                                        const std::vector<PlannedFieldStep>& unionBranches) {
                                                        emitDeserializeUnion(w,
                                                                             section,
                                                                             unionBranches,
                                                                             "out_obj",
                                                                             sectionFacts,
                                                                             renderIR.helperBindings);
                                                    };
                                                callbacks.onFieldAlignment = [this,
                                                                              &w](const std::int64_t alignmentBits) {
                                                    emitAlignDeserialize(w, alignmentBits);
                                                };
                                                callbacks.onField = [this, &w, &fieldScope](
                                                                        const PlannedFieldStep& fieldStep) {
                                                    const auto* const field = fieldStep.field;
                                                    emitDeserializeValue(w,
                                                                         field->resolvedType,
                                                                         "out_obj->" +
                                                                             fieldScope.get(IdentifierRole::FieldName,
                                                                                            field->name),
                                                                         fieldStep.arrayLengthPrefixBits,
                                                                         fieldStep.fieldFacts);
                                                };
                                                callbacks.onPaddingAlignment = [this,
                                                                                &w](const std::int64_t alignmentBits) {
                                                    emitAlignDeserialize(w, alignmentBits);
                                                };
                                                callbacks.onPadding = [this, &w](const PlannedFieldStep& fieldStep) {
                                                    const auto* const field = fieldStep.field;
                                                    emitDeserializePadding(w, field->resolvedType);
                                                };
                                                return callbacks;
                                            },
                                            [this, &w]() {
                                                emitAlignDeserialize(w, 8);
                                                w.line("*inout_buffer_size_bytes = "
                                                       "static_cast<std::size_t>(dsdl_runtime_choose_min(offset_bits, "
                                                       "capacity_bits) / 8U);");
                                                w.line("return static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS);");
                                            }});
        if (!emitted)
        {
            w.close("}");
            w.blank();
            return;
        }
        w.close("}");
        w.blank();
    }

private:
    const EmitterContext& ctx_;
    CppFlavor             flavor_{CppFlavor::Std};
    std::size_t           id_{0};

    std::string nextName(const std::string& prefix)
    {
        return "_" + prefix + std::to_string(id_++) + "_";
    }

    static std::string helperBindingName(const std::string& helperSymbol)
    {
        return renderHelperBindingIdentifier(CodegenNamingLanguage::Cpp, helperSymbol);
    }

    static void emitMlirHelperBindings(SourceWriter&                   w,
                                       const SectionHelperBindingPlan& plan,
                                       const HelperDirection           direction,
                                       const bool                      emitCapacityCheck)
    {
        CppHelperBodySpelling spelling(w);
        for (const auto& body : buildSectionHelperBodies(
                 plan,
                 direction,
                 [](const std::string& symbol) { return helperBindingName(symbol); },
                 emitCapacityCheck))
        {
            renderHelperBody(body, spelling);
        }
    }

    static void emitSerializeMlirHelperBindings(SourceWriter& w, const SectionHelperBindingPlan& plan)
    {
        emitMlirHelperBindings(w, plan, HelperDirection::Serialize, /*emitCapacityCheck=*/true);
    }

    static void emitDeserializeMlirHelperBindings(SourceWriter& w, const SectionHelperBindingPlan& plan)
    {
        emitMlirHelperBindings(w, plan, HelperDirection::Deserialize, /*emitCapacityCheck=*/false);
    }

    std::string containerElementType(const SemanticFieldType& type) const
    {
        switch (type.scalarCategory)
        {
        case SemanticScalarCategory::Bool:
            return "bool";
        case SemanticScalarCategory::Byte:
        case SemanticScalarCategory::Utf8:
        case SemanticScalarCategory::UnsignedInt:
            return unsignedStorageType(type.bitLength);
        case SemanticScalarCategory::SignedInt:
            return signedStorageType(type.bitLength);
        case SemanticScalarCategory::Float:
            return type.bitLength == 64U ? "double" : "float";
        case SemanticScalarCategory::Void:
            return "std::uint8_t";
        case SemanticScalarCategory::Composite:
            if (type.compositeType)
            {
                return ctx_.cppQualifiedTypeName(*type.compositeType);
            }
            return "std::uint8_t";
        }
        return "std::uint8_t";
    }

    void emitAlignSerialize(SourceWriter& w, const std::int64_t alignmentBits)
    {
        if (alignmentBits <= 1)
        {
            return;
        }
        trace(EmitTraceOp::Align, alignmentBits);
        const auto alignedOffset = nextName("aligned_offset");
        const auto bitIndex      = nextName("align_bit");
        const auto err           = nextName("err");
        w.line("const std::size_t " + alignedOffset + " = (offset_bits + " + std::to_string(alignmentBits - 1) +
               "U) & ~(std::size_t)" + std::to_string(alignmentBits - 1) + "U;");
        w.open("for (std::size_t " + bitIndex + " = offset_bits; " + bitIndex + " < " + alignedOffset + "; ++" +
               bitIndex + ") {");
        w.line("const std::int8_t " + err + " = dsdl_runtime_set_bit(buffer, capacity_bytes, " + bitIndex +
               ", false);");
        w.open("if (" + err + " < 0) {");
        w.line("return " + err + ";");
        w.close("}");
        w.close("}");
        w.line("offset_bits = " + alignedOffset + ";");
    }

    void emitAlignDeserialize(SourceWriter& w, const std::int64_t alignmentBits) const
    {
        if (alignmentBits <= 1)
        {
            return;
        }
        trace(EmitTraceOp::Align, alignmentBits);
        w.line("offset_bits = (offset_bits + " + std::to_string(alignmentBits - 1) + "U) & ~(std::size_t)" +
               std::to_string(alignmentBits - 1) + "U;");
    }

    void emitSerializePadding(SourceWriter& w, const SemanticFieldType& type)
    {
        if (type.bitLength == 0)
        {
            return;
        }
        trace(EmitTraceOp::Pad, type.bitLength);
        const auto err = nextName("err");
        w.line("const std::int8_t " + err + " = dsdl_runtime_set_uxx(buffer, capacity_bytes, offset_bits, 0U, " +
               std::to_string(type.bitLength) + "U);");
        w.open("if (" + err + " < 0) {");
        w.line("return " + err + ";");
        w.close("}");
        trace(EmitTraceOp::Advance, type.bitLength);
        w.line("offset_bits += " + std::to_string(type.bitLength) + "U;");
    }

    void emitDeserializePadding(SourceWriter& w, const SemanticFieldType& type) const
    {
        if (type.bitLength == 0)
        {
            return;
        }
        trace(EmitTraceOp::Pad, type.bitLength);
        trace(EmitTraceOp::Advance, type.bitLength);
        w.line("offset_bits += " + std::to_string(type.bitLength) + "U;");
    }

    /// @brief C++ spelling of the shared union-prologue steps (see EmitStep.h).
    ///
    /// Dispatch is an if / else-if chain (not a switch), so the case spelling is
    /// stateful via the shared renderer's firstCase flag, and the bad-tag default
    /// is the trailing `else` arm.
    class UnionSpelling final : public UnionSectionSpelling
    {
    public:
        UnionSpelling(FunctionBodyEmitter&            owner,
                      SourceWriter&                   w,
                      const std::string&              objRef,
                      const std::int64_t              tagBits,
                      const SectionHelperBindingPlan& helperBindings)
            : owner_(owner)
            , w_(w)
            , objRef_(objRef)
            , tagBits_(tagBits)
            , helperBindings_(helperBindings)
        {
        }

        void spellSerializeValidateTag() override
        {
            const auto validateHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(helperBindings_.unionTagValidate->symbol);
            const auto validateErr = owner_.nextName("err_union_tag");
            owner_.trace(EmitTraceOp::ValidateTag);
            w_.line("const std::int8_t " + validateErr + " = " + validateHelper + "(static_cast<std::int64_t>(" +
                    objRef_ + "->_tag_));");
            w_.open("if (" + validateErr + " != static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS)) {");
            w_.line("return " + validateErr + ";");
            w_.close("}");
        }

        void spellSerializeWriteMaskedTag() override
        {
            const auto tagHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(helperBindings_.unionTagMask->symbol);
            const auto tagExpr = tagHelper + "(static_cast<std::uint64_t>(" + objRef_ + "->_tag_))";
            const auto tagErr  = owner_.nextName("err");
            owner_.trace(EmitTraceOp::MaskTag);
            owner_.trace(EmitTraceOp::WriteTag, tagBits_);
            w_.line("const std::int8_t " + tagErr + " = dsdl_runtime_set_uxx(buffer, capacity_bytes, offset_bits, " +
                    tagExpr + ", " + std::to_string(tagBits_) + "U);");
            w_.open("if (" + tagErr + " < 0) {");
            w_.line("return " + tagErr + ";");
            w_.close("}");
        }

        void spellDeserializeReadMaskStoreTag() override
        {
            const auto rawTag = owner_.nextName("tag_raw");
            owner_.trace(EmitTraceOp::ReadTag, tagBits_);
            w_.line("const std::uint64_t " + rawTag + " = static_cast<std::uint64_t>(" +
                    unsignedGetter(static_cast<std::uint32_t>(tagBits_)) + "(buffer, capacity_bytes, offset_bits, " +
                    std::to_string(tagBits_) + "U));");
            const auto tagHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(helperBindings_.unionTagMask->symbol);
            owner_.trace(EmitTraceOp::MaskTag);
            owner_.trace(EmitTraceOp::StoreTag);
            w_.line(objRef_ + "->_tag_ = static_cast<" + unsignedStorageType(static_cast<std::uint32_t>(tagBits_)) +
                    ">(" + tagHelper + "(" + rawTag + "));");
        }

        void spellDeserializeValidateTag() override
        {
            const auto validateHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(helperBindings_.unionTagValidate->symbol);
            const auto validateErr = owner_.nextName("err_union_tag");
            owner_.trace(EmitTraceOp::ValidateTag);
            w_.line("const std::int8_t " + validateErr + " = " + validateHelper + "(static_cast<std::int64_t>(" +
                    objRef_ + "->_tag_));");
            w_.open("if (" + validateErr + " != static_cast<std::int8_t>(DSDL_RUNTIME_SUCCESS)) {");
            w_.line("return " + validateErr + ";");
            w_.close("}");
        }

        void spellAdvanceTag() override
        {
            owner_.trace(EmitTraceOp::Advance, tagBits_);
            w_.line("offset_bits += " + std::to_string(tagBits_) + "U;");
        }

        void spellBeginDispatch() override
        {
            // The if / else-if chain has no opening construct; SWITCH is abstract here.
            owner_.trace(EmitTraceOp::Switch);
        }

        void spellBeginCase(const std::int64_t optionIndex, const bool firstCase) override
        {
            owner_.trace(EmitTraceOp::Case, optionIndex);
            w_.open(std::string(firstCase ? "if" : "else if") + " (" + objRef_ +
                    "->_tag_ == " + std::to_string(optionIndex) + "U) {");
        }

        void spellEndCase() override
        {
            w_.close("}");
        }

        void spellBadTagDefault() override
        {
            owner_.trace(EmitTraceOp::DefaultBadTag);
            w_.open("else {");
            w_.line("return static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_REPRESENTATION_BAD_UNION_TAG);");
            w_.close("}");
        }

        void spellEndDispatch() override
        {
            // The trailing else arm closed itself; nothing further.
        }

    private:
        FunctionBodyEmitter&            owner_;
        SourceWriter&                   w_;
        const std::string&              objRef_;
        const std::int64_t              tagBits_;
        const SectionHelperBindingPlan& helperBindings_;
    };

    void emitSerializeUnion(SourceWriter&                        w,
                            const SemanticSection&               section,
                            const std::vector<PlannedFieldStep>& unionBranches,
                            const std::string&                   objRef,
                            const LoweredSectionFacts* const     sectionFacts,
                            const SectionHelperBindingPlan&      helperBindings)
    {
        const NamingScope            fieldScope = makeSectionFieldScope(CodegenNamingLanguage::Cpp, section);
        const auto                   tagBits    = resolveUnionTagBits(section, sectionFacts);
        UnionSpelling                spelling(*this, w, objRef, static_cast<std::int64_t>(tagBits), helperBindings);
        std::vector<UnionCaseRender> cases;
        cases.reserve(unionBranches.size());
        for (const auto& step : unionBranches)
        {
            const auto& field = *step.field;
            cases.push_back(UnionCaseRender{field.unionOptionIndex, [this, &w, &objRef, &step, &field, &fieldScope]() {
                                                const auto member =
                                                    fieldScope.get(IdentifierRole::FieldName, field.name);
                                                emitAlignSerialize(w, field.resolvedType.alignmentBits);
                                                // NOLINTBEGIN(performance-inefficient-string-concatenation)
                                                emitSerializeValue(w,
                                                                   field.resolvedType,
                                                                   objRef + "->" + member,
                                                                   step.arrayLengthPrefixBits,
                                                                   step.fieldFacts);
                                                // NOLINTEND(performance-inefficient-string-concatenation)
                                            }});
        }
        renderUnionSection(EmitTraceDirection::Serialize, cases, spelling);
    }

    void emitDeserializeUnion(SourceWriter&                        w,
                              const SemanticSection&               section,
                              const std::vector<PlannedFieldStep>& unionBranches,
                              const std::string&                   objRef,
                              const LoweredSectionFacts* const     sectionFacts,
                              const SectionHelperBindingPlan&      helperBindings)
    {
        const NamingScope            fieldScope = makeSectionFieldScope(CodegenNamingLanguage::Cpp, section);
        const auto                   tagBits    = resolveUnionTagBits(section, sectionFacts);
        UnionSpelling                spelling(*this, w, objRef, static_cast<std::int64_t>(tagBits), helperBindings);
        std::vector<UnionCaseRender> cases;
        cases.reserve(unionBranches.size());
        for (const auto& step : unionBranches)
        {
            const auto& field = *step.field;
            cases.push_back(UnionCaseRender{field.unionOptionIndex, [this, &w, &objRef, &step, &field, &fieldScope]() {
                                                const auto member =
                                                    fieldScope.get(IdentifierRole::FieldName, field.name);
                                                emitAlignDeserialize(w, field.resolvedType.alignmentBits);
                                                // NOLINTBEGIN(performance-inefficient-string-concatenation)
                                                emitDeserializeValue(w,
                                                                     field.resolvedType,
                                                                     objRef + "->" + member,
                                                                     step.arrayLengthPrefixBits,
                                                                     step.fieldFacts);
                                                // NOLINTEND(performance-inefficient-string-concatenation)
                                            }});
        }
        renderUnionSection(EmitTraceDirection::Deserialize, cases, spelling);
    }

    /// @brief C++ spelling of the shared recursive field-body steps (see EmitStep.h).
    ///
    /// Leaf statement idioms only; all cross-group and recursive ordering comes
    /// from renderFieldSteps. Fixed arrays are std::array, so the D2 length guard
    /// is type-system-subsumed (spellFixedArrayLenCheck is a documented no-op),
    /// and fixed bool arrays take the D3 bulk-copy fast path via
    /// trySpellArrayBulkFastPath. PMR flavor differences stay inside this class.
    class FieldSpelling final : public FieldStepSpelling
    {
    public:
        FieldSpelling(FunctionBodyEmitter& owner, SourceWriter& w, const HelperBindingDirection direction)
            : owner_(owner)
            , w_(w)
            , direction_(direction)
        {
        }

        void spellPad(const FieldEmitStep& step) override
        {
            if (direction_ == HelperBindingDirection::Serialize)
            {
                owner_.emitSerializePadding(w_, step.type);
            }
            else
            {
                owner_.emitDeserializePadding(w_, step.type);
            }
        }

        void spellScalarSerialize(const FieldEmitStep& step, const std::string& expr) override
        {
            switch (step.kind)
            {
            case FieldStepKind::ScalarBool: {
                const auto err = owner_.nextName("err");
                owner_.trace(EmitTraceOp::WriteScalarBool, 1);
                w_.line("const std::int8_t " + err + " = dsdl_runtime_set_bit(buffer, capacity_bytes, offset_bits, " +
                        expr + ");");
                w_.open("if (" + err + " < 0) {");
                w_.line("return " + err + ";");
                w_.close("}");
                owner_.trace(EmitTraceOp::Advance, 1);
                w_.line("offset_bits += 1U;");
                break;
            }
            case FieldStepKind::ScalarUint: {
                std::string valueExpr = "static_cast<std::uint64_t>(" + expr + ")";
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                valueExpr         = helper + "(" + valueExpr + ")";
                const auto err    = owner_.nextName("err");
                owner_.trace(EmitTraceOp::WriteScalarUint, step.bits);
                w_.line("const std::int8_t " + err + " = dsdl_runtime_set_uxx(buffer, capacity_bytes, offset_bits, " +
                        valueExpr + ", " + std::to_string(step.bits) + "U);");
                w_.open("if (" + err + " < 0) {");
                w_.line("return " + err + ";");
                w_.close("}");
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            case FieldStepKind::ScalarSint: {
                std::string valueExpr = "static_cast<std::int64_t>(" + expr + ")";
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                valueExpr         = helper + "(" + valueExpr + ")";
                const auto err    = owner_.nextName("err");
                owner_.trace(EmitTraceOp::WriteScalarSint, step.bits);
                w_.line("const std::int8_t " + err + " = dsdl_runtime_set_ixx(buffer, capacity_bytes, offset_bits, " +
                        valueExpr + ", " + std::to_string(step.bits) + "U);");
                w_.open("if (" + err + " < 0) {");
                w_.line("return " + err + ";");
                w_.close("}");
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            case FieldStepKind::ScalarFloat: {
                const auto  err            = owner_.nextName("err");
                const auto  floatType      = std::string(step.bits == 64 ? "double" : "float");
                std::string normalizedExpr = "static_cast<" + floatType + ">(" + expr + ")";
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                normalizedExpr    = helper + "(" + normalizedExpr + ")";
                std::string call;
                if (step.bits == 16)
                {
                    call = "dsdl_runtime_set_f16(buffer, capacity_bytes, offset_bits, " + normalizedExpr + ")";
                }
                else if (step.bits == 32)
                {
                    call = "dsdl_runtime_set_f32(buffer, capacity_bytes, offset_bits, " + normalizedExpr + ")";
                }
                else
                {
                    call = "dsdl_runtime_set_f64(buffer, capacity_bytes, offset_bits, " + normalizedExpr + ")";
                }
                owner_.trace(EmitTraceOp::WriteScalarFloat, step.bits);
                w_.line("const std::int8_t " + err + " = " + call + ";");
                w_.open("if (" + err + " < 0) {");
                w_.line("return " + err + ";");
                w_.close("}");
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            default:
                assert(false && "not a scalar step");
                break;
            }
        }

        void spellScalarDeserialize(const FieldEmitStep& step, const std::string& expr) override
        {
            switch (step.kind)
            {
            case FieldStepKind::ScalarBool:
                owner_.trace(EmitTraceOp::ReadScalarBool, 1);
                w_.line(expr + " = dsdl_runtime_get_bit(buffer, capacity_bytes, offset_bits);");
                owner_.trace(EmitTraceOp::Advance, 1);
                w_.line("offset_bits += 1U;");
                break;
            case FieldStepKind::ScalarUint: {
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                const auto raw    = owner_.nextName("raw");
                owner_.trace(EmitTraceOp::ReadScalarUint, step.bits);
                w_.line("const std::uint64_t " + raw + " = static_cast<std::uint64_t>(" +
                        unsignedGetter(static_cast<std::uint32_t>(step.bits)) +
                        "(buffer, capacity_bytes, offset_bits, " + std::to_string(step.bits) + "U));");
                w_.line(expr + " = static_cast<" + unsignedStorageType(static_cast<std::uint32_t>(step.bits)) + ">(" +
                        helper + "(" + raw + "));");
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            case FieldStepKind::ScalarSint: {
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                const auto raw    = owner_.nextName("raw");
                owner_.trace(EmitTraceOp::ReadScalarSint, step.bits);
                w_.line("const std::int64_t " + raw + " = static_cast<std::int64_t>(" +
                        unsignedGetter(static_cast<std::uint32_t>(step.bits)) +
                        "(buffer, capacity_bytes, offset_bits, " + std::to_string(step.bits) + "U));");
                w_.line(expr + " = static_cast<" + signedStorageType(static_cast<std::uint32_t>(step.bits)) + ">(" +
                        helper + "(" + raw + "));");
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            case FieldStepKind::ScalarFloat: {
                assert(!step.scalarHelperSymbol.empty());
                const auto helper = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.scalarHelperSymbol);
                owner_.trace(EmitTraceOp::ReadScalarFloat, step.bits);
                if (step.bits == 16)
                {
                    w_.line(expr + " = static_cast<float>(" + helper +
                            "(static_cast<float>(dsdl_runtime_get_f16(buffer, capacity_bytes, "
                            "offset_bits))));");
                }
                else if (step.bits == 32)
                {
                    w_.line(expr + " = static_cast<float>(" + helper +
                            "(static_cast<float>(dsdl_runtime_get_f32(buffer, capacity_bytes, "
                            "offset_bits))));");
                }
                else
                {
                    w_.line(expr + " = static_cast<double>(" + helper +
                            "(static_cast<double>(dsdl_runtime_get_f64(buffer, capacity_bytes, "
                            "offset_bits))));");
                }
                owner_.trace(EmitTraceOp::Advance, step.bits);
                w_.line("offset_bits += " + std::to_string(step.bits) + "U;");
                break;
            }
            default:
                assert(false && "not a scalar step");
                break;
            }
        }

        void spellFixedArrayLenCheck(const FieldEmitStep& step, const std::string& expr) override
        {
            // D2: C++ fixed arrays are std::array; the exact-length guard is subsumed
            // by the type system, so there is no emit site.
            (void) step;
            (void) expr;
        }

        bool trySpellArrayBulkFastPath(const FieldEmitStep&         step,
                                       const std::string&           expr,
                                       const HelperBindingDirection direction) override
        {
            // D3: fixed bool arrays are bit-copied wholesale instead of looping.
            if (step.kind != FieldStepKind::FixedArray || step.children.front().kind != FieldStepKind::ScalarBool)
            {
                return false;
            }
            const auto countExpr = std::to_string(step.capacity) + "U";
            if (direction == HelperBindingDirection::Serialize)
            {
                const auto source = expr + ".data()";
                owner_.trace(EmitTraceOp::BulkCopy, step.capacity);
                w_.line("dsdl_runtime_copy_bits(&buffer[0], offset_bits, " + countExpr + ", " + source + ", 0U);");
                owner_.trace(EmitTraceOp::Advance, step.capacity);
                w_.line("offset_bits += " + countExpr + ";");
            }
            else
            {
                const auto target = expr + ".data()";
                owner_.trace(EmitTraceOp::BulkCopy, step.capacity);
                w_.line("dsdl_runtime_get_bits(" + target +
                        ", &buffer[0], capacity_bytes, "
                        "offset_bits, " +
                        countExpr + ");");
                owner_.trace(EmitTraceOp::Advance, step.capacity);
                w_.line("offset_bits += " + countExpr + ";");
            }
            return true;
        }

        void spellVariableArrayLenSerialize(const FieldEmitStep& step, const std::string& expr) override
        {
            assert(step.arrayHelpers.has_value());
            assert(!step.arrayHelpers->validateSymbol.empty());
            const auto validateHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(step.arrayHelpers->validateSymbol);
            const auto validateRc = owner_.nextName("len_rc");
            owner_.trace(EmitTraceOp::LenValidate, step.prefixBits);
            w_.line("const std::int8_t " + validateRc + " = " + validateHelper + "(static_cast<std::int64_t>(" + expr +
                    ".size()));");
            w_.open("if (" + validateRc + " < 0) {");
            w_.line("return " + validateRc + ";");
            w_.close("}");

            std::string prefixExpr = "static_cast<std::uint64_t>(" + expr + ".size())";
            assert(!step.arrayHelpers->prefixSymbol.empty());
            const auto serPrefixHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(step.arrayHelpers->prefixSymbol);
            prefixExpr     = serPrefixHelper + "(" + prefixExpr + ")";
            const auto err = owner_.nextName("err");
            owner_.trace(EmitTraceOp::LenWrite, step.prefixBits);
            w_.line("const std::int8_t " + err + " = dsdl_runtime_set_uxx(buffer, capacity_bytes, offset_bits, " +
                    prefixExpr + ", " + std::to_string(step.prefixBits) + "U);");
            w_.open("if (" + err + " < 0) {");
            w_.line("return " + err + ";");
            w_.close("}");
            owner_.trace(EmitTraceOp::Advance, step.prefixBits);
            w_.line("offset_bits += " + std::to_string(step.prefixBits) + "U;");
        }

        std::string spellVariableArrayLenDeserialize(const FieldEmitStep& step, const std::string& expr) override
        {
            const auto rawCountVar = owner_.nextName("count_raw");
            owner_.trace(EmitTraceOp::LenRead, step.prefixBits);
            w_.line("const std::uint64_t " + rawCountVar + " = static_cast<std::uint64_t>(" +
                    unsignedGetter(step.prefixBits) + "(buffer, capacity_bytes, offset_bits, " +
                    std::to_string(step.prefixBits) + "U));");
            owner_.trace(EmitTraceOp::Advance, step.prefixBits);
            w_.line("offset_bits += " + std::to_string(step.prefixBits) + "U;");
            std::string countRawExpr = rawCountVar;
            assert(step.arrayHelpers.has_value());
            assert(!step.arrayHelpers->prefixSymbol.empty());
            const auto deserPrefixHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(step.arrayHelpers->prefixSymbol);
            countRawExpr        = deserPrefixHelper + "(" + countRawExpr + ")";
            const auto countVar = owner_.nextName("count");
            w_.line("const std::size_t " + countVar + " = static_cast<std::size_t>(" + countRawExpr + ");");

            assert(!step.arrayHelpers->validateSymbol.empty());
            const auto validateHelper =
                llvmdsdl::FunctionBodyEmitter::helperBindingName(step.arrayHelpers->validateSymbol);
            const auto validateRc = owner_.nextName("len_rc");
            owner_.trace(EmitTraceOp::LenValidate, step.prefixBits);
            w_.line("const std::int8_t " + validateRc + " = " + validateHelper + "(static_cast<std::int64_t>(" +
                    countVar + "));");
            w_.open("if (" + validateRc + " < 0) {");
            w_.line("return " + validateRc + ";");
            w_.close("}");
            if (isPmrFlavor(owner_.flavor_))
            {
                const auto tmpVar = owner_.nextName("tmp");
                w_.line("std::pmr::vector<" + owner_.containerElementType(step.type) + "> " + tmpVar +
                        "(effective_memory_resource != nullptr ? effective_memory_resource : "
                        "::llvmdsdl::cpp::default_memory_resource());");
                w_.line(tmpVar + ".resize(" + countVar + ");");
                w_.line(expr + " = std::move(" + tmpVar + ");");
            }
            else
            {
                w_.line(expr + ".resize(" + countVar + ");");
            }

            if (isPmrFlavor(owner_.flavor_) && step.type.scalarCategory == SemanticScalarCategory::Composite)
            {
                const auto initIndex = owner_.nextName("i");
                w_.open("for (std::size_t " + initIndex + " = 0U; " + initIndex + " < " + countVar + "; ++" +
                        initIndex + ") {");
                w_.line(expr + "[" + initIndex + "].set_memory_resource(effective_memory_resource);");
                w_.close("}");
            }

            return countVar;
        }

        std::string spellFixedArrayCountDeserialize(const FieldEmitStep& step, const std::string& expr) override
        {
            // std::array needs no storage prep; the loop bounds on the capacity literal.
            (void) expr;
            return std::to_string(step.capacity) + "U";
        }

        std::string spellBeginElemLoopSerialize(const FieldEmitStep& step, const std::string& expr) override
        {
            const auto index = owner_.nextName("index");
            const auto bound =
                step.kind == FieldStepKind::VariableArray ? (expr + ".size()") : std::to_string(step.capacity) + "U";
            owner_.trace(EmitTraceOp::ElemLoop);
            w_.open("for (std::size_t " + index + " = 0U; " + index + " < " + bound + "; ++" + index + ") {");
            return expr + "[" + index + "]";
        }

        std::string spellBeginElemLoopDeserialize(const FieldEmitStep& step,
                                                  const std::string&   expr,
                                                  const std::string&   countExpr) override
        {
            (void) step;
            const auto index = owner_.nextName("index");
            owner_.trace(EmitTraceOp::ElemLoop);
            w_.open("for (std::size_t " + index + " = 0U; " + index + " < " + countExpr + "; ++" + index + ") {");
            return expr + "[" + index + "]";
        }

        void spellEndElemLoopSerialize(const FieldEmitStep& step, const std::string& expr) override
        {
            (void) step;
            (void) expr;
            w_.close("}");
        }

        void spellEndElemLoopDeserialize(const FieldEmitStep& step, const std::string& expr) override
        {
            (void) step;
            (void) expr;
            w_.close("}");
        }

        void spellCompositeSerialize(const FieldEmitStep& step, const std::string& expr) override
        {
            if (!step.type.compositeType)
            {
                w_.line("return static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
                return;
            }

            owner_.trace(step.type.compositeSealed ? EmitTraceOp::CompositeInline : EmitTraceOp::CompositeDelimHeader);
            const auto nestedType = owner_.ctx_.cppQualifiedTypeName(*step.type.compositeType);
            auto       sizeVar    = owner_.nextName("size_bytes");
            auto       errVar     = owner_.nextName("err");

            if (!step.type.compositeSealed)
            {
                w_.line("offset_bits += 32U;  // Delimiter header");
            }

            w_.line("std::size_t " + sizeVar + " = " + std::to_string((step.type.bitLengthSet.max() + 7) / 8) + "U;");
            if (!step.type.compositeSealed)
            {
                const auto remaining = owner_.nextName("remaining");
                w_.line("const std::size_t " + remaining +
                        " = capacity_bytes - dsdl_runtime_choose_min(offset_bits / 8U, capacity_bytes);");
                assert(!step.delimiterValidateSymbol.empty());
                const auto helper     = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.delimiterValidateSymbol);
                const auto validateRc = owner_.nextName("rc");
                w_.line("const std::int8_t " + validateRc + " = " + helper + "(static_cast<std::int64_t>(" + sizeVar +
                        "), static_cast<std::int64_t>(" + remaining + "));");
                w_.open("if (" + validateRc + " < 0) {");
                w_.line("return " + validateRc + ";");
                w_.close("}");
            }
            w_.line("std::int8_t " + errVar + " = " + nestedType + "_serialize_(&" + expr +
                    ", &buffer[offset_bits / 8U], &" + sizeVar +
                    (isPmrFlavor(owner_.flavor_) ? ", effective_memory_resource" : "") + ");");
            w_.open("if (" + errVar + " < 0) {");
            w_.line("return " + errVar + ";");
            w_.close("}");

            if (!step.type.compositeSealed)
            {
                auto hdrErr = owner_.nextName("err");
                w_.line("const std::int8_t " + hdrErr +
                        " = dsdl_runtime_set_uxx(buffer, capacity_bytes, offset_bits - 32U, "
                        "static_cast<std::uint64_t>(" +
                        sizeVar + "), 32U);");
                w_.open("if (" + hdrErr + " < 0) {");
                w_.line("return " + hdrErr + ";");
                w_.close("}");
            }

            w_.line("offset_bits += " + sizeVar + " * 8U;");
        }

        void spellCompositeDeserialize(const FieldEmitStep& step, const std::string& expr) override
        {
            if (!step.type.compositeType)
            {
                w_.line("return static_cast<std::int8_t>(-DSDL_RUNTIME_ERROR_INVALID_ARGUMENT);");
                return;
            }

            owner_.trace(step.type.compositeSealed ? EmitTraceOp::CompositeInline : EmitTraceOp::CompositeDelimHeader);
            const auto nestedType = owner_.ctx_.cppQualifiedTypeName(*step.type.compositeType);
            auto       sizeVar    = owner_.nextName("size_bytes");
            auto       errVar     = owner_.nextName("err");

            if (!step.type.compositeSealed)
            {
                w_.line("std::size_t " + sizeVar +
                        " = static_cast<std::size_t>(dsdl_runtime_get_u32(buffer, capacity_bytes, "
                        "offset_bits, "
                        "32U));");
                w_.line("offset_bits += 32U;");
                w_.line("const std::size_t _remaining_" + std::to_string(owner_.id_) +
                        " = capacity_bytes - dsdl_runtime_choose_min(offset_bits / 8U, capacity_bytes);");
                const auto remVar = "_remaining_" + std::to_string(owner_.id_);
                ++owner_.id_;
                assert(!step.delimiterValidateSymbol.empty());
                const auto helper     = llvmdsdl::FunctionBodyEmitter::helperBindingName(step.delimiterValidateSymbol);
                const auto validateRc = owner_.nextName("rc");
                w_.line("const std::int8_t " + validateRc + " = " + helper + "(static_cast<std::int64_t>(" + sizeVar +
                        "), static_cast<std::int64_t>(" + remVar + "));");
                w_.open("if (" + validateRc + " < 0) {");
                w_.line("return " + validateRc + ";");
                w_.close("}");
                const auto consumed = owner_.nextName("consumed");
                w_.line("std::size_t " + consumed + " = " + sizeVar + ";");
                w_.line("const std::int8_t " + errVar + " = " + nestedType + "_deserialize_(&" + expr +
                        ", &buffer[offset_bits / 8U], &" + consumed +
                        (isPmrFlavor(owner_.flavor_) ? ", effective_memory_resource" : "") + ");");
                w_.open("if (" + errVar + " < 0) {");
                w_.line("return " + errVar + ";");
                w_.close("}");
                w_.line("offset_bits += " + sizeVar + " * 8U;");
                return;
            }

            w_.line("std::size_t " + sizeVar +
                    " = capacity_bytes - dsdl_runtime_choose_min(offset_bits / 8U, capacity_bytes);");
            w_.line("const std::int8_t " + errVar + " = " + nestedType + "_deserialize_(&" + expr +
                    ", &buffer[offset_bits / 8U], &" + sizeVar +
                    (isPmrFlavor(owner_.flavor_) ? ", effective_memory_resource" : "") + ");");
            w_.open("if (" + errVar + " < 0) {");
            w_.line("return " + errVar + ";");
            w_.close("}");
            w_.line("offset_bits += " + sizeVar + " * 8U;");
        }

    private:
        FunctionBodyEmitter&         owner_;
        SourceWriter&                w_;
        const HelperBindingDirection direction_;
    };

    void emitSerializeValue(SourceWriter&                      w,
                            const SemanticFieldType&           type,
                            const std::string&                 expr,
                            const std::optional<std::uint32_t> arrayLengthPrefixBitsOverride = std::nullopt,
                            const LoweredFieldFacts* const     fieldFacts                    = nullptr)
    {
        const auto steps =
            buildFieldEmitSteps(type, fieldFacts, arrayLengthPrefixBitsOverride, HelperBindingDirection::Serialize);
        FieldSpelling spelling(*this, w, HelperBindingDirection::Serialize);
        renderFieldSteps(steps, expr, HelperBindingDirection::Serialize, spelling);
    }

    void emitDeserializeValue(SourceWriter&                      w,
                              const SemanticFieldType&           type,
                              const std::string&                 expr,
                              const std::optional<std::uint32_t> arrayLengthPrefixBitsOverride = std::nullopt,
                              const LoweredFieldFacts* const     fieldFacts                    = nullptr)
    {
        const auto steps =
            buildFieldEmitSteps(type, fieldFacts, arrayLengthPrefixBitsOverride, HelperBindingDirection::Deserialize);
        FieldSpelling spelling(*this, w, HelperBindingDirection::Deserialize);
        renderFieldSteps(steps, expr, HelperBindingDirection::Deserialize, spelling);
    }
};

std::string cppTypeFromFieldType(const SemanticFieldType& type, const EmitterContext& ctx)
{
    switch (type.scalarCategory)
    {
    case SemanticScalarCategory::Bool:
        return "bool";
    case SemanticScalarCategory::Byte:
    case SemanticScalarCategory::Utf8:
    case SemanticScalarCategory::UnsignedInt:
        return unsignedStorageType(type.bitLength);
    case SemanticScalarCategory::SignedInt:
        return signedStorageType(type.bitLength);
    case SemanticScalarCategory::Float:
        if (type.bitLength == 64U)
        {
            return "double";
        }
        return "float";
    case SemanticScalarCategory::Void:
        return "std::uint8_t";
    case SemanticScalarCategory::Composite:
        if (type.compositeType)
        {
            return ctx.cppQualifiedTypeName(*type.compositeType);
        }
        return "std::uint8_t";
    }
    return "std::uint8_t";
}

void emitArrayMetadata(SourceWriter& w, const SemanticSection& section)
{
    const NamingScope constScope = makeSectionConstantScope(CodegenNamingLanguage::Cpp, section);
    for (const auto& field : section.fields)
    {
        if (field.isPadding || field.resolvedType.arrayKind == ArrayKind::None)
        {
            continue;
        }
        const auto named = [&](const ArrayMetadataKind kind) {
            return constScope.get(IdentifierRole::MacroName,
                                  arrayMetadataName(CodegenNamingLanguage::Cpp, field.name, kind));
        };
        w.line("static constexpr std::size_t " + named(ArrayMetadataKind::Capacity) + " = " +
               std::to_string(field.resolvedType.arrayCapacity) + "U;");
        w.line("static constexpr bool " + named(ArrayMetadataKind::IsVariableLength) + " = " +
               std::string(isVariableArray(field.resolvedType.arrayKind) ? "true" : "false") + ";");
    }
}

void emitFunctionPrototypes(SourceWriter& w, const std::string& typeName, const CppFlavor flavor)
{
    w.line("struct " + typeName + ";");
    w.line("inline std::int8_t " + typeName + "_serialize_(const " + typeName +
           "* obj, std::uint8_t* buffer, std::size_t* inout_buffer_size_bytes" +
           (isPmrFlavor(flavor) ? ", ::llvmdsdl::cpp::MemoryResource* memory_resource" : "") + ");");
    w.line("inline std::int8_t " + typeName + "_deserialize_(" + typeName +
           "* out_obj, const std::uint8_t* buffer, std::size_t* inout_buffer_size_bytes" +
           (isPmrFlavor(flavor) ? ", ::llvmdsdl::cpp::MemoryResource* memory_resource" : "") + ");");
    w.line("inline std::int8_t " + typeName +
           "_try_deserialize_view_(const std::uint8_t* buffer, std::size_t* inout_buffer_size_bytes, "
           "const std::uint8_t** out_view_bytes);");
    w.line("inline std::int8_t " + typeName +
           "_try_serialize_view_(const std::uint8_t* view_bytes, std::size_t view_size_bytes, "
           "std::uint8_t* buffer, std::size_t* inout_buffer_size_bytes);");
    w.blank();
}

void emitSectionStruct(SourceWriter&                    w,
                       const std::string&               typeName,
                       const std::string&               fullName,
                       std::uint32_t                    majorVersion,
                       std::uint32_t                    minorVersion,
                       const SemanticSection&           section,
                       const EmitterContext&            ctx,
                       const CppFlavor                  flavor,
                       const AttachedDoc&               typeDoc,
                       const LoweredSectionFacts* const sectionFacts)
{
    const NamingScope fieldScope = makeSectionFieldScope(CodegenNamingLanguage::Cpp, section);
    emitAttachedDocCpp(w, typeDoc);
    const std::string structAttribute =
        (section.deprecated && ctx.emitDeprecationAttributes()) ? "[[deprecated]] " : "";
    w.open("struct " + structAttribute + typeName + " {");

    std::size_t              emitted = 0;
    std::vector<std::string> variableArrayMembers;
    std::vector<std::string> compositeScalarMembers;
    std::vector<std::string> compositeFixedArrayMembers;
    std::vector<std::string> compositeVariableArrayMembers;

    for (const auto& field : section.fields)
    {
        if (field.isPadding)
        {
            continue;
        }

        const auto member   = fieldScope.get(IdentifierRole::FieldName, field.name);
        const auto baseType = cppTypeFromFieldType(field.resolvedType, ctx);
        emitAttachedDocCpp(w, field.doc);

        if (field.resolvedType.arrayKind == ArrayKind::None)
        {
            // NOLINTNEXTLINE(performance-inefficient-string-concatenation)
            w.line(baseType + " " + member + "{};");
            if (isPmrFlavor(flavor) && field.resolvedType.scalarCategory == SemanticScalarCategory::Composite)
            {
                compositeScalarMembers.push_back(member);
            }
            ++emitted;
            continue;
        }

        if (field.resolvedType.arrayKind == ArrayKind::Fixed)
        {
            if (field.resolvedType.scalarCategory == SemanticScalarCategory::Bool)
            {
                w.line("std::array<std::uint8_t, (" + std::to_string(field.resolvedType.arrayCapacity) +
                       "U + 7U) / 8U> " + member + "{};");
            }
            else
            {
                // NOLINTBEGIN(performance-inefficient-string-concatenation)
                w.line("std::array<" + baseType + ", " + std::to_string(field.resolvedType.arrayCapacity) + "U> " +
                       member + "{};");
                // NOLINTEND(performance-inefficient-string-concatenation)
            }
            if (isPmrFlavor(flavor) && field.resolvedType.scalarCategory == SemanticScalarCategory::Composite)
            {
                compositeFixedArrayMembers.push_back(member);
            }
            ++emitted;
            continue;
        }

        if (isPmrFlavor(flavor))
        {
            w.line("std::pmr::vector<" +
                   std::string(field.resolvedType.scalarCategory == SemanticScalarCategory::Bool ? "bool" : baseType) +
                   "> " + member + "{};");
            variableArrayMembers.push_back(member);
            if (field.resolvedType.scalarCategory == SemanticScalarCategory::Composite)
            {
                compositeVariableArrayMembers.push_back(member);
            }
        }
        else if (isAutosarFlavor(flavor))
        {
            w.line("::llvmdsdl::cpp::autosar::BoundedVector<" +
                   std::string(field.resolvedType.scalarCategory == SemanticScalarCategory::Bool ? "bool" : baseType) +
                   ", " + std::to_string(field.resolvedType.arrayCapacity) + "U> " + member + "{};");
        }
        else
        {
            w.line("std::vector<" +
                   std::string(field.resolvedType.scalarCategory == SemanticScalarCategory::Bool ? "bool" : baseType) +
                   "> " + member + "{};");
        }
        ++emitted;
    }

    if (section.isUnion)
    {
        // Tag storage must match the wire tag width (uint8 for <=256 options, uint16 for
        // 257..65536, etc.); a hardcoded uint8 truncates a wide tag and mis-dispatches.
        w.line(unsignedStorageType(resolveUnionTagBits(section, sectionFacts)) + " _tag_{0U};");
        ++emitted;
    }

    if (isPmrFlavor(flavor))
    {
        w.line("::llvmdsdl::cpp::MemoryResource* _memory_resource{::llvmdsdl::cpp::default_memory_resource()};");
        w.line(typeName + "() = default;");
        w.line("explicit " + typeName +
               "(::llvmdsdl::cpp::MemoryResource* memory_resource) { set_memory_resource(memory_resource); }");
        w.open("void set_memory_resource(::llvmdsdl::cpp::MemoryResource* memory_resource) {");
        w.line("_memory_resource = (memory_resource != nullptr) ? memory_resource : "
               "::llvmdsdl::cpp::default_memory_resource();");
        for (const auto& member : variableArrayMembers)
        {
            // NOLINTNEXTLINE(performance-inefficient-string-concatenation)
            w.line(member + " = decltype(" + member + ")(_memory_resource);");
        }
        for (const auto& member : compositeScalarMembers)
        {
            w.line(member + ".set_memory_resource(_memory_resource);");
        }
        for (const auto& member : compositeFixedArrayMembers)
        {
            const auto i =
                codegenProjectIdentifier(CodegenNamingLanguage::Cpp, IdentifierRole::LocalName, member + "_index");
            // NOLINTBEGIN(performance-inefficient-string-concatenation)
            w.open("for (std::size_t " + i + " = 0U; " + i + " < " + member + ".size(); ++" + i + ") {");
            w.line(member + "[" + i + "].set_memory_resource(_memory_resource);");
            // NOLINTEND(performance-inefficient-string-concatenation)
            w.close("}");
        }
        for (const auto& member : compositeVariableArrayMembers)
        {
            const auto i =
                codegenProjectIdentifier(CodegenNamingLanguage::Cpp, IdentifierRole::LocalName, member + "_index");
            // NOLINTBEGIN(performance-inefficient-string-concatenation)
            w.open("for (std::size_t " + i + " = 0U; " + i + " < " + member + ".size(); ++" + i + ") {");
            w.line(member + "[" + i + "].set_memory_resource(_memory_resource);");
            // NOLINTEND(performance-inefficient-string-concatenation)
            w.close("}");
        }
        w.close("}");
        ++emitted;
    }

    if (emitted == 0)
    {
        w.line("std::uint8_t _dummy_{0U};");
    }

    w.line("static constexpr const char* FULL_NAME = \"" + fullName + "\";");
    w.line("static constexpr bool IS_DEPRECATED = " + std::string(section.deprecated ? "true" : "false") + ";");
    w.line("static constexpr const char* FULL_NAME_AND_VERSION = \"" + fullName + "." + std::to_string(majorVersion) +
           "." + std::to_string(minorVersion) + "\";");
    w.line("static constexpr std::size_t EXTENT_BYTES = " + std::to_string(section.extentBits.value_or(0) / 8) + "U;");
    w.line("static constexpr std::size_t SERIALIZATION_BUFFER_SIZE_BYTES = " +
           std::to_string((section.serializationBufferSizeBits + 7) / 8) + "U;");
    const bool        zohAliasEligible = sectionFacts != nullptr && sectionFacts->zohAliasEligible;
    const std::string zohAliasReason   = (sectionFacts != nullptr && !sectionFacts->zohAliasReason.empty())
                                             ? sectionFacts->zohAliasReason
                                             : "not-proven";
    w.line(std::string("static constexpr bool ZOH_ALIAS_ELIGIBLE = ") + (zohAliasEligible ? "true;" : "false;"));
    w.line("static constexpr const char* ZOH_ALIAS_REASON = \"" + zohAliasReason + "\";");
    if (section.isUnion)
    {
        std::size_t optionCount = 0;
        for (const auto& f : section.fields)
        {
            if (!f.isPadding)
            {
                ++optionCount;
            }
        }
        w.line("static constexpr std::size_t UNION_OPTION_COUNT = " + std::to_string(optionCount) + "U;");
    }

    // Two DSDL constants can upper-case onto one name; a duplicate `static constexpr` does not

    // compile. The generated statics are claimed by the ConstantName role's policy, so a DSDL

    // constant named FULL_NAME is escaped before it reaches the scope.

    NamingScope const constScope = makeSectionConstantScope(CodegenNamingLanguage::Cpp, section);

    for (const auto& c : section.constants)
    {
        emitAttachedDocCpp(w, c.doc);
        w.line("static constexpr auto " + constScope.get(IdentifierRole::ConstantName, c.name) + " = " +
               valueToCppExpr(c.type, c.value) + ";");
    }

    emitArrayMetadata(w, section);

    w.open("LLVMDSDL_NODISCARD inline std::int8_t serialize(std::uint8_t* buffer, std::size_t* "
           "inout_buffer_size_bytes) "
           "const {");
    if (isPmrFlavor(flavor))
    {
        w.line("return " + typeName + "_serialize_(this, buffer, inout_buffer_size_bytes, _memory_resource);");
    }
    else
    {
        w.line("return " + typeName + "_serialize_(this, buffer, inout_buffer_size_bytes);");
    }
    w.close("}");

    w.open("LLVMDSDL_NODISCARD inline std::int8_t deserialize(const std::uint8_t* buffer, std::size_t* "
           "inout_buffer_size_bytes) {");
    if (isPmrFlavor(flavor))
    {
        w.line("return " + typeName + "_deserialize_(this, buffer, inout_buffer_size_bytes, _memory_resource);");
    }
    else
    {
        w.line("return " + typeName + "_deserialize_(this, buffer, inout_buffer_size_bytes);");
    }
    w.close("}");

    w.open("LLVMDSDL_NODISCARD static inline std::int8_t try_deserialize_view(const std::uint8_t* buffer, "
           "std::size_t* inout_buffer_size_bytes, const std::uint8_t** out_view_bytes) {");
    w.line("return " + typeName + "_try_deserialize_view_(buffer, inout_buffer_size_bytes, out_view_bytes);");
    w.close("}");
    w.open("LLVMDSDL_NODISCARD static inline std::int8_t try_serialize_view(const std::uint8_t* view_bytes, "
           "std::size_t view_size_bytes, std::uint8_t* buffer, std::size_t* inout_buffer_size_bytes) {");
    w.line("return " + typeName +
           "_try_serialize_view_(view_bytes, view_size_bytes, buffer, inout_buffer_size_bytes);");
    w.close("}");

    if (isPmrFlavor(flavor))
    {
        w.open("LLVMDSDL_NODISCARD inline std::int8_t serialize(std::uint8_t* buffer, std::size_t* "
               "inout_buffer_size_bytes, ::llvmdsdl::cpp::MemoryResource* memory_resource) const {");
        w.line("return " + typeName + "_serialize_(this, buffer, inout_buffer_size_bytes, memory_resource);");
        w.close("}");

        w.open("LLVMDSDL_NODISCARD inline std::int8_t deserialize(const std::uint8_t* buffer, std::size_t* "
               "inout_buffer_size_bytes, ::llvmdsdl::cpp::MemoryResource* memory_resource) {");
        w.line("return " + typeName + "_deserialize_(this, buffer, inout_buffer_size_bytes, memory_resource);");
        w.close("}");
    }

    w.close("};");
    w.blank();
}

void emitViewFunctions(SourceWriter& w, const std::string& typeName)
{
    w.line("inline std::int8_t " + typeName +
           "_try_deserialize_view_(const std::uint8_t* const buffer, std::size_t* const "
           "inout_buffer_size_bytes, const std::uint8_t** const out_view_bytes)");
    w.open("{");
    w.open("if ((buffer == nullptr) || (inout_buffer_size_bytes == nullptr) || (out_view_bytes == nullptr)) {");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.close("}");
    w.line("*out_view_bytes = nullptr;");
    w.line("constexpr std::size_t required = " + typeName + "::SERIALIZATION_BUFFER_SIZE_BYTES;");
    w.open("if (*inout_buffer_size_bytes < required) {");
    w.line("*inout_buffer_size_bytes = required;");
    w.line("return -DSDL_RUNTIME_ERROR_SERIALIZATION_BUFFER_TOO_SMALL;");
    w.close("}");
    w.open("#if defined(LLVMDSDL_TARGET_ENDIANNESS_BIG)");
    w.line("*inout_buffer_size_bytes = 0U;");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.midway("#else");
    w.open("if (" + typeName + "::ZOH_ALIAS_ELIGIBLE) {");
    w.line("*out_view_bytes = buffer;");
    w.line("*inout_buffer_size_bytes = required;");
    w.line("return DSDL_RUNTIME_SUCCESS;");
    w.close("}");
    w.line("*inout_buffer_size_bytes = 0U;");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.close("#endif");
    w.close("}");
    w.blank();

    w.line("inline std::int8_t " + typeName +
           "_try_serialize_view_(const std::uint8_t* const view_bytes, const std::size_t view_size_bytes, "
           "std::uint8_t* const buffer, std::size_t* const inout_buffer_size_bytes)");
    w.open("{");
    w.open("if ((view_bytes == nullptr) || (buffer == nullptr) || (inout_buffer_size_bytes == nullptr)) {");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.close("}");
    w.line("constexpr std::size_t required = " + typeName + "::SERIALIZATION_BUFFER_SIZE_BYTES;");
    w.open("if (view_size_bytes != required) {");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.close("}");
    w.open("if (*inout_buffer_size_bytes < required) {");
    w.line("*inout_buffer_size_bytes = required;");
    w.line("return -DSDL_RUNTIME_ERROR_SERIALIZATION_BUFFER_TOO_SMALL;");
    w.close("}");
    w.open("#if defined(LLVMDSDL_TARGET_ENDIANNESS_BIG)");
    w.line("*inout_buffer_size_bytes = 0U;");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.midway("#else");
    w.open("if (" + typeName + "::ZOH_ALIAS_ELIGIBLE) {");
    w.line("std::memcpy(buffer, view_bytes, required);");
    w.line("*inout_buffer_size_bytes = required;");
    w.line("return DSDL_RUNTIME_SUCCESS;");
    w.close("}");
    w.line("*inout_buffer_size_bytes = 0U;");
    w.line("return -DSDL_RUNTIME_ERROR_INVALID_ARGUMENT;");
    w.close("#endif");
    w.close("}");
    w.blank();
}

void emitSection(SourceWriter&                    w,
                 const EmitterContext&            ctx,
                 const SemanticDefinition&        def,
                 const std::string&               typeName,
                 const std::string&               fullName,
                 const SemanticSection&           section,
                 const CppFlavor                  flavor,
                 const AttachedDoc&               typeDoc,
                 const LoweredSectionFacts* const sectionFacts)
{
    emitFunctionPrototypes(w, typeName, flavor);
    emitSectionStruct(w,
                      typeName,
                      fullName,
                      def.info.majorVersion,
                      def.info.minorVersion,
                      section,
                      ctx,
                      flavor,
                      docWithDeprecationNotice(typeDoc,
                                               section.deprecated,
                                               def.info.fullName,
                                               def.info.majorVersion,
                                               def.info.minorVersion),
                      sectionFacts);

    const auto canonicalSectionName =
        fullName + "." + std::to_string(def.info.majorVersion) + "." + std::to_string(def.info.minorVersion);
    FunctionBodyEmitter bodyEmitter(ctx, flavor);
    ctx.traceSection(canonicalSectionName, EmitTraceDirection::Serialize);
    bodyEmitter.emitSerializeFunction(w, typeName, section, sectionFacts);
    ctx.traceSection(canonicalSectionName, EmitTraceDirection::Deserialize);
    bodyEmitter.emitDeserializeFunction(w, typeName, section, sectionFacts);
    emitViewFunctions(w, typeName);
}

llvm::Expected<std::string> loadCRuntimeHeader()
{
    if (const auto data = embedded_runtime::find("dsdl_runtime.h"))
    {
        return std::string(*data);
    }
    return llvm::createStringError(llvm::inconvertibleErrorCode(), "embedded runtime source missing: dsdl_runtime.h");
}

llvm::Expected<std::string> loadCppRuntimeHeader(const CppFlavor flavor)
{
    const std::string_view relativeRuntimeHeader =
        isAutosarFlavor(flavor) ? "cpp/autosar/dsdl_runtime.hpp" : "cpp/dsdl_runtime.hpp";
    if (const auto data = embedded_runtime::find(relativeRuntimeHeader))
    {
        return std::string(*data);
    }
    return llvm::createStringError(llvm::inconvertibleErrorCode(),
                                   "embedded runtime source missing: %s",
                                   std::string(relativeRuntimeHeader).c_str());
}

std::string renderHeader(const SemanticDefinition& def,
                         const EmitterContext&     ctx,
                         const CppFlavor           flavor,
                         const LoweredFactsMap&    loweredFacts)
{
    std::ostringstream out;
    SourceWriter       w            = makeCppWriter(out);
    const auto         guard        = headerGuard(def.info);
    const auto         baseTypeName = ctx.cppTypeName(def);

    out << generatedCommentLine("C++ backend") << "\n";
    out << "// Source: " << def.info.fullName << "." << def.info.majorVersion << "." << def.info.minorVersion << "\n\n";
    out << "#ifndef " << guard << "\n";
    out << "#define " << guard << "\n\n";

    // Under the unversioned scheme this type's name carries no version, so two versions of it are
    // one identifier. Generating both is fine -- they are separate headers -- but including both is
    // not, and saying so here beats a cascade of redefinitions from inside generated code.
    if (ctx.typeNameVersioning() == TypeNameVersioning::Unversioned)
    {
        const auto [anyVersion, thisVersion] = renderVersionSentinelMacros(CodegenNamingLanguage::Cpp,
                                                                           def.info.fullName,
                                                                           def.info.majorVersion,
                                                                           def.info.minorVersion);
        out << "#if defined(" << anyVersion << ") && !defined(" << thisVersion << ")\n";
        out << "#  error \"" << def.info.fullName
            << ": two versions of one type in one translation unit, but generated type names are "
               "unversioned. Regenerate with --versioned-type-names to use both.\"\n";
        out << "#endif\n";
        out << "#define " << anyVersion << "\n";
        out << "#define " << thisVersion << "\n\n";
    }

    out << "#include <array>\n";
    out << "#include <cstddef>\n";
    out << "#include <cstdint>\n";
    out << "#include <cstring>\n";
    out << "#include <utility>\n";
    if (!isAutosarFlavor(flavor))
    {
        out << "#include <vector>\n";
    }
    if (isPmrFlavor(flavor))
    {
        out << "#include <memory_resource>\n";
    }
    out << "#include \"dsdl_runtime.hpp\"\n";

    for (const auto& depRef : collectDefinitionCompositeDependencies(def))
    {
        if (const auto* dep = ctx.find(depRef))
        {
            out << "#include \"" << llvmdsdl::EmitterContext::relativeHeaderPath(*dep) << "\"\n";
        }
    }
    w.blank();

    // Generated code must never warn about itself; see the C backend for the three ways a deprecated
    // type is referenced from within its own generated file. The region closes before the include
    // guard, so user code naming the type still gets the diagnostic.
    if (ctx.emitDeprecationAttributes())
    {
        out << "#pragma GCC diagnostic push\n";
        out << "#pragma GCC diagnostic ignored \"-Wdeprecated-declarations\"\n\n";
    }

    emitNamespaceOpen(w, def.info.namespaceComponents);

    if (def.isService)
    {
        // A single underscore: C++ reserves any identifier containing `__`, and these name C++
        // structs. The C emitter keeps `__` for its own service section types, where it is legal.
        const auto requestType  = baseTypeName + renderSectionTypeSuffix(CodegenNamingLanguage::Cpp, "request");
        const auto responseType = baseTypeName + renderSectionTypeSuffix(CodegenNamingLanguage::Cpp, "response");

        w.line("constexpr const char* " + baseTypeName + "_FULL_NAME = \"" + def.info.fullName + "\";");
        w.line("constexpr const char* " + baseTypeName + "_FULL_NAME_AND_VERSION = \"" + def.info.fullName + "." +
               std::to_string(def.info.majorVersion) + "." + std::to_string(def.info.minorVersion) + "\";");
        w.blank();

        emitSection(w,
                    ctx,
                    def,
                    requestType,
                    def.info.fullName + ".Request",
                    def.request,
                    flavor,
                    def.doc,
                    lookupLoweredSectionFacts(loweredFacts, def, "request"));
        if (def.response)
        {
            emitSection(w,
                        ctx,
                        def,
                        responseType,
                        def.info.fullName + ".Response",
                        *def.response,
                        flavor,
                        def.doc,
                        lookupLoweredSectionFacts(loweredFacts, def, "response"));
        }

        w.line("using " + baseTypeName + " = " + requestType + ";");
        w.line("constexpr std::size_t " + baseTypeName + "_EXTENT_BYTES = " + requestType + "::EXTENT_BYTES;");
        w.line("constexpr std::size_t " + baseTypeName + "_SERIALIZATION_BUFFER_SIZE_BYTES = " + requestType +
               "::SERIALIZATION_BUFFER_SIZE_BYTES;");
        w.line("constexpr bool " + baseTypeName + "_ZOH_ALIAS_ELIGIBLE = " + requestType + "::ZOH_ALIAS_ELIGIBLE;");
        w.line("constexpr const char* " + baseTypeName + "_ZOH_ALIAS_REASON = " + requestType + "::ZOH_ALIAS_REASON;");
        w.blank();

        w.line("inline std::int8_t " + baseTypeName + "_serialize_(const " + baseTypeName +
               "* const obj, std::uint8_t* const buffer, std::size_t* const "
               "inout_buffer_size_bytes" +
               (isPmrFlavor(flavor) ? ", ::llvmdsdl::cpp::MemoryResource* const memory_resource" : "") + ")");
        w.open("{");
        w.line("return " + requestType + "_serialize_(reinterpret_cast<const " + requestType +
               "*>(obj), buffer, inout_buffer_size_bytes" + (isPmrFlavor(flavor) ? ", memory_resource" : "") + ");");
        w.close("}");
        w.blank();

        w.line("inline std::int8_t " + baseTypeName + "_deserialize_(" + baseTypeName +
               "* const out_obj, const std::uint8_t* buffer, std::size_t* const "
               "inout_buffer_size_bytes" +
               (isPmrFlavor(flavor) ? ", ::llvmdsdl::cpp::MemoryResource* const memory_resource" : "") + ")");
        w.open("{");
        w.line("return " + requestType + "_deserialize_(reinterpret_cast<" + requestType +
               "*>(out_obj), buffer, inout_buffer_size_bytes" + (isPmrFlavor(flavor) ? ", memory_resource" : "") +
               ");");
        w.close("}");
        w.blank();

        w.line("inline std::int8_t " + baseTypeName +
               "_try_deserialize_view_(const std::uint8_t* const buffer, std::size_t* const "
               "inout_buffer_size_bytes, const std::uint8_t** const out_view_bytes)");
        w.open("{");
        w.line("return " + requestType + "_try_deserialize_view_(buffer, inout_buffer_size_bytes, out_view_bytes);");
        w.close("}");
        w.blank();

        w.line("inline std::int8_t " + baseTypeName +
               "_try_serialize_view_(const std::uint8_t* const view_bytes, const std::size_t view_size_bytes, "
               "std::uint8_t* const buffer, std::size_t* const inout_buffer_size_bytes)");
        w.open("{");
        w.line("return " + requestType +
               "_try_serialize_view_(view_bytes, view_size_bytes, buffer, inout_buffer_size_bytes);");
        w.close("}");
    }
    else
    {
        emitSection(w,
                    ctx,
                    def,
                    baseTypeName,
                    def.info.fullName,
                    def.request,
                    flavor,
                    def.doc,
                    lookupLoweredSectionFacts(loweredFacts, def, ""));
    }

    emitNamespaceClose(w, def.info.namespaceComponents);
    if (ctx.emitDeprecationAttributes())
    {
        out << "\n#pragma GCC diagnostic pop\n";
    }
    out << "\n#endif /* " << guard << " */\n";
    return out.str();
}

llvm::Error emitProfile(const SemanticModule&                  semantic,
                        const std::filesystem::path&           outRoot,
                        const CppFlavor                        flavor,
                        const LoweredFactsMap&                 loweredFacts,
                        const CppEmitOptions&                  options,
                        const std::unordered_set<std::string>& selectedTypeKeys,
                        EmitTraceSink* const                   traceSink)
{
    // Support artifacts are rendered from content compiled into this binary, so whether to write
    // them is independent of which definitions were selected -- except under `as-needed`, which
    // ties them to there being type code to support.
    bool anyTypeEmitted = false;
    for (const auto& def : semantic.definitions)
    {
        if (shouldEmitDefinition(def.info, selectedTypeKeys, options.supportGeneration))
        {
            anyTypeEmitted = true;
            break;
        }
    }

    if (shouldEmitSupport(options.supportGeneration, anyTypeEmitted))
    {
        auto cRuntime = loadCRuntimeHeader();
        if (!cRuntime)
        {
            return cRuntime.takeError();
        }
        if (auto err =
                writeGeneratedFile(outRoot / "dsdl_runtime.h",
                                   generatedCommentLine("C runtime scaffold for C++ backend") + "\n\n" + *cRuntime,
                                   options.writePolicy))
        {
            return err;
        }

        auto cppRuntime = loadCppRuntimeHeader(flavor);
        if (!cppRuntime)
        {
            return cppRuntime.takeError();
        }
        if (auto err = writeGeneratedFile(outRoot / "dsdl_runtime.hpp",
                                          generatedCommentLine("C++ runtime scaffold") + "\n\n" + *cppRuntime,
                                          options.writePolicy))
        {
            return err;
        }
    }

    EmitterContext ctx(semantic, options.emitDeprecationAttributes, options.typeNameVersioning);
    ctx.setTraceSink(traceSink);
    for (const auto& def : semantic.definitions)
    {
        if (!shouldEmitDefinition(def.info, selectedTypeKeys, options.supportGeneration))
        {
            continue;
        }
        const std::vector<std::string> requiredTypeKeys{definitionTypeKey(def.info)};

        std::filesystem::path dir = outRoot;
        for (const auto& ns : def.info.namespaceComponents)
        {
            dir /= ns;
        }
        if (auto err = writeGeneratedFile(dir / headerFileName(def.info),
                                          renderHeader(def, ctx, flavor, loweredFacts),
                                          options.writePolicy,
                                          requiredTypeKeys))
        {
            return err;
        }
    }

    return llvm::Error::success();
}

