llvm::Error emitTs(const SemanticModule& semantic,
                   mlir::ModuleOp        module,
                   const TsEmitOptions&  options,
                   DiagnosticEngine&     diagnostics,
                   EmitTraceSink*        traceSink)
{
    if (options.outDir.empty())
    {
        return llvm::createStringError(llvm::inconvertibleErrorCode(), "output directory is required");
    }

    const auto mlirCoverageDiagnostic =
        codegen_diagnostic_text::mlirSchemaCoverageValidationFailedForEmission("TypeScript");
    LoweredFactsMap loweredFacts;
    if (!collectLoweredFactsFromMlir(semantic,
                                     module,
                                     diagnostics,
                                     "TypeScript",
                                     &loweredFacts,
                                     options.optimizeLoweredSerDes))
    {
        return llvm::createStringError(llvm::inconvertibleErrorCode(), "%s", mlirCoverageDiagnostic.c_str());
    }

    std::filesystem::path const outRoot(options.outDir);
    const auto                  selectedTypeKeys = makeTypeKeySet(options.selectedTypeKeys);

    // Support artifacts are rendered from content compiled into this binary, so whether to write
    // them is independent of which definitions were selected -- except under `as-needed`, which
    // ties them to there being type code to support.
    bool anyTypeEmitted = false;
    for (const auto& def : semantic.definitions)
    {
        if (shouldEmitDefinition(def.info, selectedTypeKeys, options.supportGeneration))
        {
            anyTypeEmitted = true;
            break;
        }
    }
    const bool emitSupport = shouldEmitSupport(options.supportGeneration, anyTypeEmitted);

    if (emitSupport)
    {
        if (options.emitPackageJson)
        {
            if (auto err =
                    writeGeneratedFile(outRoot / "package.json", renderPackageJson(options), options.writePolicy))
            {
                return err;
            }
        }
        if (auto err = writeGeneratedFile(outRoot / "dsdl_runtime.ts",
                                          renderTsRuntimeModule(options.runtimeSpecialization),
                                          options.writePolicy))
        {
            return err;
        }
    }

    EmitterContext ctx(semantic, options.typeNameVersioning);
    ctx.setTraceSink(traceSink);

    std::vector<const SemanticDefinition*> ordered;
    ordered.reserve(semantic.definitions.size());
    for (const auto& def : semantic.definitions)
    {
        if (!shouldEmitDefinition(def.info, selectedTypeKeys, options.supportGeneration))
        {
            continue;
        }
        ordered.push_back(&def);
    }
    std::ranges::sort(ordered, [](const auto* lhs, const auto* rhs) {
        if (lhs->info.fullName != rhs->info.fullName)
        {
            return lhs->info.fullName < rhs->info.fullName;
        }
        if (lhs->info.majorVersion != rhs->info.majorVersion)
        {
            return lhs->info.majorVersion < rhs->info.majorVersion;
        }
        return lhs->info.minorVersion < rhs->info.minorVersion;
    });

    std::vector<std::filesystem::path> generatedRelativePaths;
    generatedRelativePaths.reserve(ordered.size());

    for (const auto* def : ordered)
    {
        const std::vector<std::string> requiredTypeKeys{definitionTypeKey(def->info)};
        const auto                     relPath = llvmdsdl::EmitterContext::relativeFilePath(def->info);
        generatedRelativePaths.push_back(relPath);

        const auto fullPath = outRoot / relPath;
        auto       rendered = renderDefinitionFile(*def, ctx, loweredFacts);
        if (!rendered)
        {
            return rendered.takeError();
        }

        if (auto err = writeGeneratedFile(fullPath, *rendered, options.writePolicy, requiredTypeKeys))
        {
            return err;
        }
    }

    std::ostringstream index;
    SourceWriter       indexW = makeTsWriter(index);
    indexW.line(generatedCommentLine("TypeScript backend index"));
    std::map<std::string, unsigned> aliasUseCount;
    for (const auto& relPath : generatedRelativePaths)
    {
        std::string modulePath = relPath.generic_string();
        if (modulePath.size() >= 3 && modulePath.ends_with(".ts"))
        {
            modulePath.resize(modulePath.size() - 3);
        }
        std::string alias    = moduleAliasFromPath(modulePath);
        unsigned&   useCount = aliasUseCount[alias];
        if (useCount > 0)
        {
            alias += "_" + std::to_string(useCount);
        }
        ++useCount;

        // NOLINTNEXTLINE(performance-inefficient-string-concatenation)
        indexW.line("export * as " + alias + " from \"./" + modulePath + "\";");
    }

    if (auto err = writeGeneratedFile(outRoot / "index.ts", index.str(), options.writePolicy, options.selectedTypeKeys))
    {
        return err;
    }

    return llvm::Error::success();
}

