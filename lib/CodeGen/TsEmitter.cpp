void emitAttachedDocTs(SourceWriter& w, const AttachedDoc& doc)
{
    for (const auto& line : doc.lines)
    {
        w.line("// " + line.text);
    }
}

/// @brief TypeScript spelling of the helper body shapes (see HelperBodyPlan.h).
///
/// Guards answer with a boolean rather than a status code, which is what the
/// generated call sites test. Integer helpers marshal through `bigint` because a
/// `number` cannot hold a 64-bit wire value, and hand back whichever of the two the
/// caller passed in.
class TsHelperBodySpelling final : public HelperBodySpelling
{
public:
    explicit TsHelperBodySpelling(SourceWriter& w)
        : w_(w)
    {
    }

    void spellIdentity(const HelperBody& body) override
    {
        w_.line("const " + body.symbol + " = " + signature(body) + " => value;");
    }

    void spellMask(const HelperBody& body) override
    {
        marshalled(body, "const masked = raw & " + mask(body.bits) + ";", "masked");
    }

    void spellSaturateUnsigned(const HelperBody& body) override
    {
        marshalled(body,
                   "const clamped = raw < 0n ? 0n : (raw > " + mask(body.bits) + " ? " + mask(body.bits) + " : raw);",
                   "clamped");
    }

    void spellSaturateSigned(const HelperBody& body) override
    {
        const auto lo = std::to_string(body.minValue) + "n";
        const auto hi = std::to_string(body.maxValue) + "n";
        marshalled(body,
                   "const clamped = raw < " + lo + " ? " + lo + " : (raw > " + hi + " ? " + hi + " : raw);",
                   "clamped");
    }

    void spellSignExtend(const HelperBody& body) override
    {
        const auto bitMask = mask(body.bits);
        const auto signBit = std::to_string(std::uint64_t{1} << (body.bits - 1U)) + "n";
        w_.open("const " + body.symbol + " = " + signature(body) + " => {");
        w_.line("const raw = ((typeof value === \"bigint\") ? value : BigInt(Math.trunc(value))) & " + bitMask + ";");
        w_.line("const signed = (raw & " + signBit + ") !== 0n ? (raw | (~" + bitMask + ")) : raw;");
        w_.line("return (typeof value === \"bigint\") ? signed : Number(signed);");
        w_.close("};");
    }

    void spellStatusGuard(const HelperBody& body) override
    {
        switch (body.guard)
        {
        case HelperGuardKind::CapacityTooSmall:
            w_.line("const " + body.symbol + " = (capacityBits: number): boolean => " +
                    std::to_string(body.requiredBits) + " <= capacityBits;");
            break;
        case HelperGuardKind::ArrayLengthOutOfRange:
            w_.line("const " + body.symbol +
                    " = (value: number): boolean => (value >= 0) && (value <= " + std::to_string(body.capacity) + ");");
            break;
        case HelperGuardKind::DelimiterOutOfRange:
            w_.line("const " + body.symbol +
                    " = (payloadBytes: number, remainingBytes: number): boolean => (payloadBytes >= 0) && "
                    "(payloadBytes <= remainingBytes);");
            break;
        }
    }

    void spellTagMembership(const HelperBody& body) override
    {
        if (body.allowedTags.empty())
        {
            w_.line("const " + body.symbol + " = (_tagValue: number): boolean => false;");
            return;
        }
        std::string condition;
        for (const auto tag : body.allowedTags)
        {
            if (!condition.empty())
            {
                condition += " || ";
            }
            condition += "(tagValue === " + std::to_string(tag) + ")";
        }
        w_.line("const " + body.symbol + " = (tagValue: number): boolean => " + condition + ";");
    }

private:
    static std::string mask(const std::uint32_t bits)
    {
        return renderU64MaskLiteral(HelperBindingRenderLanguage::TypeScript, bits);
    }

    static std::string signature(const HelperBody& body)
    {
        switch (body.signature)
        {
        case HelperSignature::UnsignedToUnsigned:
        case HelperSignature::SignedToSigned:
            return "(value: number | bigint): number | bigint";
        case HelperSignature::Float32:
        case HelperSignature::Float64:
            return "(value: number): number";
        case HelperSignature::ValueToStatus:
        case HelperSignature::PairToStatus:
            break;
        }
        return "(value: number): boolean";
    }

    /// @brief A body that converts to bigint, computes, and converts back.
    void marshalled(const HelperBody& body, const std::string& compute, const std::string& result)
    {
        w_.open("const " + body.symbol + " = " + signature(body) + " => {");
        w_.line("const raw = (typeof value === \"bigint\") ? value : BigInt(Math.trunc(value));");
        w_.line(compute);
        w_.line("return (typeof value === \"bigint\") ? " + result + " : Number(" + result + ");");
        w_.close("};");
    }

    SourceWriter& w_;
};

class EmitterContext final
{
public:
    EmitterContext(const SemanticModule& semantic, const TypeNameVersioning typeNameVersioning)
        : index_(semantic)
        , typeNameVersioning_(typeNameVersioning)
    {
    }

    /// @brief Whether generated type names carry the definition's version.
    TypeNameVersioning typeNameVersioning() const
    {
        return typeNameVersioning_;
    }

    /// @brief Attaches an emit-order trace sink (for the emit-order verifier). Null (default) disables tracing at zero
    /// cost.
    void setTraceSink(EmitTraceSink* const sink)
    {
        traceSink_ = sink;
    }

    /// @brief Records one abstract emit op into the attached sink (no-op when unattached).
    ///
    /// Const because it appends to the sink pointee, not the pointer, so it is callable on
    /// the `const EmitterContext&` the free render functions receive.
    template <typename PayloadT = std::int64_t>
    void trace(const EmitTraceOp op, const PayloadT payload = -1) const
    {
        emitTrace(traceSink_, op, static_cast<std::int64_t>(payload));
    }

    /// @brief Marks the start of one (type, direction) trace segment (no-op when unattached).
    void traceSection(const std::string& canonicalName, const EmitTraceDirection direction) const
    {
        emitTraceSection(traceSink_, canonicalName, direction);
    }

    const SemanticDefinition* find(const SemanticTypeRef& ref) const
    {
        return index_.find(ref);
    }

    static std::string namespacePath(const DiscoveredDefinition& info)
    {
        return renderNamespaceRelativePath(CodegenNamingLanguage::TypeScript, info.namespaceComponents)
            .generic_string();
    }

    std::string typeName(const DiscoveredDefinition& info) const
    {
        return renderDefinitionTypeName(CodegenNamingLanguage::TypeScript,
                                        info.namespaceComponents,
                                        info.shortName,
                                        info.majorVersion,
                                        info.minorVersion,
                                        typeNameVersioning_);
    }

    /// @brief Local name for a *referenced* type in the file currently being emitted.
    ///
    /// @details
    /// Usually the plain versioned name, which is what the import brings in. It differs when one
    /// file references two types that share a short name from different namespaces --
    /// `uavcan.si.unit.angular_velocity.Vector3.1.0` and `uavcan.si.unit.velocity.Vector3.1.0` are
    /// both `Vector3_1_0`, and importing both under that name is a duplicate-identifier error that
    /// stops `tsc` outright. Such types are imported under a namespace-qualified alias instead, and
    /// this is where every reference site picks that alias up: the type annotations, the serialize
    /// and deserialize call names, and the import list all resolve through here, so they cannot
    /// disagree.
    std::string typeName(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            if (const auto alias = importAliases_.find(importAliasKey(def->info)); alias != importAliases_.end())
            {
                return alias->second;
            }
            return typeName(def->info);
        }

        DiscoveredDefinition tmp;
        tmp.shortName    = ref.shortName;
        tmp.majorVersion = ref.majorVersion;
        tmp.minorVersion = ref.minorVersion;
        return typeName(tmp);
    }

    /// @brief Identity of a definition for alias bookkeeping: unique across namespaces and versions.
    static std::string importAliasKey(const DiscoveredDefinition& info)
    {
        return info.fullName + ":" + std::to_string(info.majorVersion) + "." + std::to_string(info.minorVersion);
    }

    /// @brief Installs the alias table for the file about to be emitted, replacing any previous one.
    void setImportAliases(std::map<std::string, std::string> aliases) const
    {
        importAliases_ = std::move(aliases);
    }

    static std::string fileStem(const DiscoveredDefinition& info)
    {
        return renderVersionedFileStem(CodegenNamingLanguage::TypeScript,
                                       info.shortName,
                                       info.majorVersion,
                                       info.minorVersion);
    }

    static std::filesystem::path relativeFilePath(const DiscoveredDefinition& info)
    {
        return renderRelativeTypeFilePath(CodegenNamingLanguage::TypeScript, info, "ts");
    }

    std::filesystem::path relativeFilePath(const SemanticTypeRef& ref) const
    {
        if (const auto* def = find(ref))
        {
            return relativeFilePath(def->info);
        }

        return renderRelativeTypeFilePath(CodegenNamingLanguage::TypeScript, ref, "ts");
    }

private:
    /// @brief Per-file alias table; see typeName(const SemanticTypeRef&). Mutable for the same
    /// reason `trace` is const: the free render functions are handed a `const EmitterContext&`.
    mutable std::map<std::string, std::string> importAliases_;

    DefinitionIndex    index_;
    TypeNameVersioning typeNameVersioning_{TypeNameVersioning::Unversioned};
    EmitTraceSink*     traceSink_ = nullptr;
};

std::string tsFieldBaseType(const SemanticFieldType& type, const EmitterContext& ctx)
{
    switch (type.scalarCategory)
    {
    case SemanticScalarCategory::Bool:
        return "boolean";
    case SemanticScalarCategory::Byte:
    case SemanticScalarCategory::Utf8:
        return "number";
    case SemanticScalarCategory::UnsignedInt:
    case SemanticScalarCategory::SignedInt:
        if (type.bitLength > 53U)
        {
            return "bigint";
        }
        return "number";
    case SemanticScalarCategory::Float:
    case SemanticScalarCategory::Void:
        return "number";
    case SemanticScalarCategory::Composite:
        if (type.compositeType)
        {
            return ctx.typeName(*type.compositeType);
        }
        return "unknown";
    }
    return "unknown";
}

std::string tsFieldType(const SemanticFieldType& type, const EmitterContext& ctx)
{
    auto base = tsFieldBaseType(type, ctx);
    if (type.arrayKind == ArrayKind::None)
    {
        return base;
    }
    return "Array<" + base + ">";
}

std::string relativeImportPath(const std::filesystem::path& fromFile, const std::filesystem::path& toFile)
{
    const auto  fromDir    = fromFile.parent_path();
    auto        rel        = toFile.lexically_relative(fromDir);
    std::string importPath = rel.generic_string();
    if (importPath.size() >= 3 && importPath.ends_with(".ts"))
    {
        importPath.resize(importPath.size() - 3);
    }
    if (!importPath.empty() && importPath.front() != '.')
    {
        importPath = "./" + importPath;
    }
    return importPath;
}

std::string moduleAliasFromPath(const std::string& modulePath)
{
    std::string alias;
    alias.reserve(modulePath.size() + 8);
    for (char const c : modulePath)
    {
        if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
        {
            alias.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(c))));
        }
        else
        {
            alias.push_back('_');
        }
    }
    // Not a role: the alias comes from --ts-module, so it is a token this generator was handed
    // rather than a DSDL name, and must not pick up a role's case projection.
    return codegenSanitizeIdentifier(CodegenNamingLanguage::TypeScript, alias.empty() ? "module" : alias);
}

void emitSectionConstants(SourceWriter& w, const std::string& prefix, const SemanticSection& section)
{
    std::vector<std::string> constNames;
    constNames.reserve(section.constants.size());
    for (const auto& constant : section.constants)
    {
        constNames.push_back(constant.name);
    }
    NamingScope const constScope = makeSectionConstantScope(CodegenNamingLanguage::TypeScript, section);
    const auto        prefixupper =
        codegenProjectIdentifier(CodegenNamingLanguage::TypeScript, IdentifierRole::ConstantName, prefix);
    for (const auto& constant : section.constants)
    {
        emitAttachedDocTs(w, constant.doc);
        const auto constName = prefixupper + "_" + constScope.get(IdentifierRole::ConstantName, constant.name);
        w.line("export const " + constName + " = " + tsConstValue(constant.type, constant.value) + ";");
    }
}

/// @brief Collision-free property names for one section's fields.
///
/// snake_casing is many-to-one, so `fooBar` and `foo_bar` both fold to `foo_bar`; without this the
/// object type would declare the same property twice and the (de)serializer would read/write the
/// wrong one. Built from `section.fields` (declaration order) so every emission site agrees.
NamingScope makeTsFieldIdents(const SemanticSection& section)
{
    std::vector<std::string> names;
    for (const auto& field : section.fields)
    {
        if (!field.isPadding)
        {
            names.push_back(field.name);
        }
    }
    return makeSectionFieldScope(CodegenNamingLanguage::TypeScript, section);
}

void emitDeprecationJsDocTs(SourceWriter&       w,
                            const bool          deprecated,
                            const std::string&  fullName,
                            const std::uint32_t majorVersion,
                            const std::uint32_t minorVersion)
{
    if (!deprecated)
    {
        return;
    }
    // The `Deprecated: ` prefix that the shared notice carries for Go's benefit is redundant next to
    // the JSDoc tag, so it is dropped here.
    const std::string notice = deprecationNotice(fullName, majorVersion, minorVersion);
    const std::string prefix = "Deprecated: ";
    const std::string body   = notice.starts_with(prefix) ? notice.substr(prefix.size()) : notice;

    // Wrapped and split across lines for the same reason the notice itself is: a single-line JSDoc
    // block would be twice the width of the code around it. Budget allows for the " * " continuation.
    const auto lines = wrapCommentText(body, 68U);
    w.line("/**");
    w.line(" * @deprecated " + lines.front());
    for (std::size_t i = 1; i < lines.size(); ++i)
    {
        w.line(" *   " + lines[i]);
    }
    w.line(" */");
}

void emitStructSectionType(SourceWriter&          w,
                           const std::string&     typeName,
                           const SemanticSection& section,
                           const AttachedDoc&     typeDoc,
                           const EmitterContext&  ctx,
                           const std::string&     fullName,
                           const std::uint32_t    majorVersion,
                           const std::uint32_t    minorVersion,
                           const bool             deprecated)
{
    emitAttachedDocTs(w, typeDoc);
    emitDeprecationJsDocTs(w, deprecated, fullName, majorVersion, minorVersion);
    w.open("export interface " + typeName + " {");
    const NamingScope fieldIdents = makeTsFieldIdents(section);
    for (const auto& field : section.fields)
    {
        if (field.isPadding)
        {
            continue;
        }
        emitAttachedDocTs(w, field.doc);
        const auto fieldName = fieldIdents.get(IdentifierRole::FieldName, field.name);
        w.line(fieldName + ": " + tsFieldType(field.resolvedType, ctx) + ";");
    }
    w.close("}");
}

void emitUnionSectionType(SourceWriter&          w,
                          const std::string&     typeName,
                          const SemanticSection& section,
                          const AttachedDoc&     typeDoc,
                          const EmitterContext&  ctx,
                          const std::string&     fullName,
                          const std::uint32_t    majorVersion,
                          const std::uint32_t    minorVersion)
{
    std::vector<const SemanticField*> options;
    for (const auto& field : section.fields)
    {
        if (!field.isPadding)
        {
            options.push_back(&field);
        }
    }

    if (options.empty())
    {
        emitAttachedDocTs(w, typeDoc);
        emitDeprecationJsDocTs(w, section.deprecated, fullName, majorVersion, minorVersion);
        w.line("export type " + typeName + " = { _tag: number };");
        return;
    }

    emitAttachedDocTs(w, typeDoc);
    emitDeprecationJsDocTs(w, section.deprecated, fullName, majorVersion, minorVersion);
    w.line("export type " + typeName + " =");
    const NamingScope fieldIdents = makeTsFieldIdents(section);
    for (std::size_t i = 0; i < options.size(); ++i)
    {
        const auto* field = options[i];
        emitAttachedDocTs(w, field->doc);
        const auto         fieldName = fieldIdents.get(IdentifierRole::FieldName, field->name);
        std::ostringstream variant;
        variant << "{ _tag: " << field->unionOptionIndex << "; " << fieldName << ": "
                << tsFieldType(field->resolvedType, ctx) << "; }";
        const auto* const prefix = "  | ";
        w.line(prefix + variant.str() + (i + 1 == options.size() ? ";" : ""));
    }
}

void emitSectionType(SourceWriter&          w,
                     const std::string&     typeName,
                     const SemanticSection& section,
                     const AttachedDoc&     typeDoc,
                     const EmitterContext&  ctx,
                     const std::string&     fullName,
                     const std::uint32_t    majorVersion,
                     const std::uint32_t    minorVersion)
{
    if (section.isUnion)
    {
        emitUnionSectionType(w, typeName, section, typeDoc, ctx, fullName, majorVersion, minorVersion);
    }
    else
    {
        emitStructSectionType(w,
                              typeName,
                              section,
                              typeDoc,
                              ctx,
                              fullName,
                              majorVersion,
                              minorVersion,
                              section.deprecated);
    }
}

