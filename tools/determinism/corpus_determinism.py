"""
Differential generated-output check.

Runs a matrix of dsdlc invocations and records a canonical per-file SHA-256 manifest of what each run
wrote. Two manifests produced by two dsdlc binaries are then compared byte for byte: identical input,
identical output, or the difference is a property of the builds rather than of the data.

Two matrices:

  languages  Every text backend over one DSDL root, given by --dsdl-root. CI compares x86-64 against
             arm64, both built from the project's own toolchain. That covers what ships -- two
             architectures of the same release -- and catches anything that lets word size,
             alignment, or floating-point formatting reach emitted text, which same-host environment
             perturbation (locale/TZ/PYTHONHASHSEED, already gated) cannot expose.

             Comparing two standard libraries instead -- libstdc++ against libc++ -- catches
             std::unordered_* iteration order leaking into output, and is the obvious-looking
             alternative. It does not fit a project that ships one toolchain: there is no such
             divergence left to measure, and check_unordered_iteration.py excludes that class at the
             source anyway.

  oracle     Every target over every corpus the project gates on: the regulated corpus, as built and
             with --optimize-lowered-serdes, the showroom, the views and accessors-only fixtures, and
             both passes of the adversarial naming corpus. The targets are C, C++ in each profile, Rust
             in each memory mode, Go, TypeScript, Python and object code, each writing its naming
             manifest, and ast and mlir, whose standard output is the product: the lowered module, and
             for ast the naming manifest of every language. CI compares the merge base of a pull
             request carrying the `surface` label against its head, so a change meant to move no
             generated byte proves that it moved none. Run by hand, it proves the same of any two
             builds.

Modes:
  generate:  --dsdlc PATH --out MANIFEST [--matrix languages] --dsdl-root DIR
             --dsdlc PATH --out MANIFEST --matrix oracle --work-dir DIR [--repo-root DIR]
             [--label NAME] [--meta k=v ...]
  compare:   --compare A.json B.json

A run that exits non-zero fails the generation, which still writes its manifest. Every run is compared
strictly: its exit code, the files it wrote and their bytes. A difference in any of them fails the
comparison with per-file detail.

The oracle runs dsdlc from the repository root with its corpora named relative to it, and writes the
generated adversarial corpus under --work-dir, so both sides read the same bytes at the same paths.
A code target's standard output is not recorded: its run summary carries the elapsed time.
Depfiles (*.d) are excluded defensively: they embed absolute host paths by design.
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

LANGUAGE_TARGETS = {
    "c": [],
    "cpp": [],
    "rust": [],
    "go": [],
    "ts": ["--ts-module", "cross_stdlib_determinism"],
    "python": [],
}

# The oracle's corpora, relative to the repository root: each corpus's roots, its options, and the
# lookup directories the ast target needs. A code or mlir target resolves a uavcan dependency from the
# embedded catalogue, which analysis alone does not load. The adversarial corpus is generated, once per
# pass, by the naming gate's own generator.
REGULATED_ROOT = "submodules/public_regulated_data_types/uavcan"
ORACLE_CORPORA = {
    "uavcan": ([REGULATED_ROOT], [], []),
    "uavcan-optimised": ([REGULATED_ROOT], ["--optimize-lowered-serdes"], []),
    "showroom": (["examples/showroom/dsdl/lanyard"], ["--allow-unregulated-fixed-port-id"], ["-I", REGULATED_ROOT]),
    "views": (["test/lit/fixtures_views"], ["--aliasable-views", "-I", "test/lit/fixtures_aliasable"], []),
    "accessors-only": (["test/lit/fixtures_aliasable"], ["--aliasable-only"], []),
}
ADVERSARIAL_GENERATOR = "test/integration/generate_naming_adversarial_corpus.py"
ADVERSARIAL_PASSES = {
    "adversarial-versioned": ([], ["--all-type-versions", "--versioned-type-names"]),
    "adversarial-unversioned": (["--no-version-multiplicity"], []),
}

# Each oracle target: the language, its options, and whether its standard output is the product.
ORACLE_TARGETS = {
    "ast": ("ast", [], True),
    "mlir": ("mlir", [], True),
    "c": ("c", [], False),
    "cpp-std": ("cpp", ["--cpp-profile", "std"], False),
    "cpp-pmr": ("cpp", ["--cpp-profile", "pmr"], False),
    "cpp-autosar": ("cpp", ["--cpp-profile", "autosar",
                            "--vocabulary", "examples/vocabulary/cpp-autosar-cetl.yaml"], False),
    "rust": ("rust", [], False),
    "rust-pool": ("rust", ["--rust-memory-mode", "inline-then-pool"], False),
    "go": ("go", ["--go-module", "m"], False),
    "ts": ("ts", ["--ts-module", "m"], False),
    "python": ("python", [], False),
    "obj": ("obj", [], False),
}

NAMING_MANIFEST = "naming-manifest.json"
STDOUT_KEY = "<stdout>"


def hash_tree(root):
    """Canonical per-file SHA-256 map over a generated tree (sorted relative paths)."""
    files = {}
    for dirpath, _, filenames in os.walk(root):
        for name in filenames:
            if name.endswith(".d"):
                continue  # depfiles embed absolute host paths by design
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            with open(path, "rb") as handle:
                files[rel] = hashlib.sha256(handle.read()).hexdigest()
    return files


def digest_of(files, exit_code):
    """One digest over a run's exit code and every file's path and hash."""
    digest = hashlib.sha256(f"exit={exit_code}\0".encode("ascii"))
    for rel in sorted(files):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(files[rel].encode("ascii"))
        digest.update(b"\0")
    return digest.hexdigest()


def language_runs(dsdl_root):
    """The languages matrix: one run per text backend over one DSDL root."""
    return [
        {"id": lang, "command": ["--target-language", lang, dsdl_root, *extra], "stdout": False}
        for lang, extra in LANGUAGE_TARGETS.items()
    ]


def generate_adversarial_corpora(repo_root, work_dir):
    """Writes both passes of the adversarial corpus under @p work_dir and answers each pass's roots."""
    corpora = {}
    for name, (generator_args, dsdlc_args) in ADVERSARIAL_PASSES.items():
        out = Path(work_dir) / name
        subprocess.run(
            [sys.executable, str(Path(repo_root) / ADVERSARIAL_GENERATOR), "--outdir", str(out), *generator_args],
            check=True, capture_output=True, text=True)
        roots = sorted(str(p) for p in out.iterdir() if p.is_dir())
        corpora[name] = (roots, dsdlc_args, [])
    return corpora


def oracle_runs(corpora):
    """The oracle matrix: every target over every corpus."""
    runs = []
    for corpus, (roots, corpus_args, analysis_lookup) in corpora.items():
        for target, (language, target_args, stdout) in ORACLE_TARGETS.items():
            lookup = analysis_lookup if language == "ast" else []
            command = ["--target-language", language, *target_args, *corpus_args, *lookup, *roots,
                       "--naming-manifest", NAMING_MANIFEST]
            runs.append({"id": f"{corpus}/{target}", "command": command, "stdout": stdout})
    return runs


def execute(dsdlc, run, out_dir, cwd):
    """Runs one dsdlc invocation into @p out_dir and answers its record and its standard error."""
    os.makedirs(out_dir, exist_ok=True)
    proc = subprocess.run([dsdlc, *run["command"], "--outdir", out_dir], cwd=cwd, capture_output=True)
    files = hash_tree(out_dir)
    if run["stdout"]:
        files[STDOUT_KEY] = hashlib.sha256(proc.stdout).hexdigest()
    record = {"exit": proc.returncode, "files": files, "digest": digest_of(files, proc.returncode)}
    return record, proc.stderr.decode("utf-8", errors="replace")


def generate(args):
    meta = {
        "label": args.label,
        "platform": sys.platform,
        "machine": platform.machine(),
    }
    for entry in args.meta:
        key, _, value = entry.partition("=")
        meta[key] = value
    version = subprocess.run([args.dsdlc, "--version"], capture_output=True, text=True)
    meta["dsdlc_version"] = version.stdout.strip()

    cwd = None
    if args.matrix == "oracle":
        cwd = args.repo_root
        corpora = dict(ORACLE_CORPORA)
        corpora.update(generate_adversarial_corpora(args.repo_root, args.work_dir))
        runs = oracle_runs(corpora)
    else:
        runs = language_runs(args.dsdl_root)

    dsdlc = os.path.abspath(args.dsdlc)
    records = {}
    errors = {}
    with tempfile.TemporaryDirectory(prefix="corpus-determinism-") as workdir:
        with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 1) as pool:
            futures = {
                run["id"]: pool.submit(execute, dsdlc, run, os.path.join(workdir, run["id"]), cwd)
                for run in runs
            }
            for run_id, future in futures.items():
                records[run_id], errors[run_id] = future.result()
    for run_id in sorted(records):
        record = records[run_id]
        print(f"  {run_id:40s} exit {record['exit']}  {len(record['files']):5d} files  {record['digest'][:16]}...")

    manifest = {"meta": meta, "matrix": args.matrix, "runs": records}
    with open(args.out, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=1, sort_keys=True)
    print(f"manifest written: {args.out} ({meta})")

    failed = sorted(run_id for run_id, record in records.items() if record["exit"] != 0)
    for run_id in failed:
        print(f"\ndsdlc failed for {run_id} (exit {records[run_id]['exit']}):\n{errors[run_id]}", file=sys.stderr)
    return 1 if failed else 0


def compare(path_a, path_b):
    with open(path_a, encoding="utf-8") as handle:
        a = json.load(handle)
    with open(path_b, encoding="utf-8") as handle:
        b = json.load(handle)
    print(f"A: {a['meta']}")
    print(f"B: {b['meta']}")

    if a.get("matrix") != b.get("matrix"):
        print(f"\nthe manifests record different matrices: {a.get('matrix')} and {b.get('matrix')}")
        return 1

    failures = []
    runs_a, runs_b = a["runs"], b["runs"]
    for run_id in sorted(set(runs_a) | set(runs_b)):
        ra, rb = runs_a.get(run_id), runs_b.get(run_id)
        if ra is None or rb is None:
            failures.append(f"[{run_id}] missing from manifest: A={ra is not None} B={rb is not None}")
            continue
        if ra["digest"] == rb["digest"]:
            print(f"  {run_id:40s} OK ({len(ra['files'])} files)")
            continue
        detail = []
        if ra["exit"] != rb["exit"]:
            detail.append(f"exit {ra['exit']} against {rb['exit']}")
        only_a = sorted(set(ra["files"]) - set(rb["files"]))
        only_b = sorted(set(rb["files"]) - set(ra["files"]))
        differing = sorted(f for f in set(ra["files"]) & set(rb["files"]) if ra["files"][f] != rb["files"][f])
        if only_a:
            detail.append(f"only in A: {only_a[:5]}{'...' if len(only_a) > 5 else ''}")
        if only_b:
            detail.append(f"only in B: {only_b[:5]}{'...' if len(only_b) > 5 else ''}")
        if differing:
            detail.append(f"content differs: {differing[:10]}{'...' if len(differing) > 10 else ''}")
        failures.append(f"[{run_id}] " + "; ".join(detail))

    if failures:
        print("\nGENERATED OUTPUT DIFFERS between the two builds:")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    print(f"\nall {len(runs_a)} runs byte-identical")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dsdlc", help="path to the dsdlc executable (generate mode)")
    ap.add_argument("--out", help="manifest output path (generate mode)")
    ap.add_argument("--matrix", choices=["languages", "oracle"], default="languages",
                    help="the runs to generate (default: languages)")
    ap.add_argument("--dsdl-root", help="DSDL namespace root to generate from (languages matrix)")
    ap.add_argument("--repo-root", default=str(Path(__file__).resolve().parents[2]),
                    help="the repository whose corpora the oracle reads (default: this script's)")
    ap.add_argument("--work-dir", help="where the oracle writes the adversarial corpus; both sides of a "
                                       "comparison name the same directory")
    ap.add_argument("--label", default="", help="human-readable side label, e.g. amd64 or merge-base")
    ap.add_argument("--meta", action="append", default=[],
                    help="extra manifest metadata as key=value (e.g. llvm=22.1.8); repeatable")
    ap.add_argument("--compare", nargs=2, metavar=("A", "B"),
                    help="compare two manifests instead of generating")
    args = ap.parse_args()

    if args.compare:
        return compare(*args.compare)
    if not (args.dsdlc and args.out):
        ap.error("generate mode requires --dsdlc and --out")
    if not os.path.exists(args.dsdlc):
        ap.error(f"dsdlc not found: {args.dsdlc}")
    if args.matrix == "languages":
        if not args.dsdl_root:
            ap.error("the languages matrix requires --dsdl-root")
        if not os.path.isdir(args.dsdl_root):
            ap.error(f"dsdl root not found: {args.dsdl_root}")
    else:
        if not args.work_dir:
            ap.error("the oracle matrix requires --work-dir")
        if not os.path.isdir(args.repo_root):
            ap.error(f"repository root not found: {args.repo_root}")
    return generate(args)


if __name__ == "__main__":
    sys.exit(main())
