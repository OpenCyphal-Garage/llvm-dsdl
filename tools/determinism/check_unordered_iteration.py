"""
Reject unjustified iteration over hashed containers in the generated-output path.

A `std::unordered_*` container's iteration order is a property of the standard
library implementation, not of the data in it. libstdc++ and libc++ hash and
bucket differently, so a loop over one can emit different bytes when built
against a different standard library -- while being perfectly deterministic for
any single binary, which is what makes it so easy to introduce and so hard to
notice.

This project publishes byte-reproducibility of generated code as a guarantee, so
that class of divergence has to be structurally excluded rather than tested for
after the fact. A differential corpus comparison (corpus_determinism.py) can only
catch it once it has already happened, and only if the two builds being compared
differ in their standard library -- which the cross-architecture gate that
replaced the old cross-stdlib one deliberately does not, since both halves come
from the same toolchain.

Iterating a hashed container is not automatically wrong. It is fine when the
result cannot inherit the order: the loop feeds an ordered container, the output
is sorted before use, or the computation is order-independent (a reachability
closure, a membership test, a sum). What is not fine is doing so silently. Mark
such a site with

    // determinism-ok: <why the order cannot reach emitted text>

on the iterating line or the line above it.

Scope is the path that can reach generated bytes. The language server is
excluded: its responses are not the byte-reproducibility guarantee, and it
iterates hashed maps constantly and legitimately.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

SCOPE = (
    "lib/CodeGen",
    "lib/Lowering",
    "lib/Transforms",
    "lib/IR",
    "lib/Frontend",
    "lib/Semantics",
    "tools/dsdlc",
    "include/llvmdsdl/CodeGen",
    "include/llvmdsdl/Frontend",
    "include/llvmdsdl/Semantics",
)

WAIVER = "determinism-ok"

# The declared name of a hashed container: the identifier that follows the type.
# Covers locals, members, parameters and references alike.
DECL = re.compile(
    r"std::unordered_(?:map|set|multimap|multiset)\s*<.*?>\s*[&*]?\s*(\w+)")

# `for (... : <range>)` -- the range expression is what must be checked, since
# it may be a member access rather than a bare identifier. Deliberately not
# anchored to end of line: a loop whose body is written on the same line is
# still a loop, and anchoring silently missed exactly that.
RANGE_FOR = re.compile(r"for\s*\(.*?:\s*([^){]+)\)")

# Names are pooled per translation unit, so an identifier can collide with a
# same-named local of a different type in another function. These algorithms
# resolve that without a waiver: none of them compiles against a hashed
# container -- they need random access, or mutable elements, or both -- so their
# presence proves the thing being iterated is a sequence.
SEQUENCE_ONLY = (
    "sort", "stable_sort", "partial_sort", "nth_element",
    "unique", "reverse", "rotate", "shuffle", "make_heap",
)


def declared_names(text: str) -> set[str]:
    return set(DECL.findall(text))


def iteration_sites(path: pathlib.Path, names: set[str]) -> list[tuple[int, str]]:
    """Lines in @p path that iterate one of @p names without a waiver."""
    if not names:
        return []
    lines = path.read_text(errors="replace").splitlines()

    def waived(index: int) -> bool:
        """Whether the line, or the comment block directly above it, waives."""
        if WAIVER in lines[index]:
            return True
        # Walk back over the contiguous comment block. A reason worth giving is
        # usually longer than one line, and requiring it to be the last line of
        # the comment would be a silly place to put it.
        cursor = index - 1
        while cursor >= 0 and lines[cursor].lstrip().startswith("//"):
            if WAIVER in lines[cursor]:
                return True
            cursor -= 1
        return False

    out: list[tuple[int, str]] = []
    for index, line in enumerate(lines):
        if waived(index):
            continue
        hit = False
        match = RANGE_FOR.search(line)
        if match:
            expression = match.group(1)
            hit = any(re.search(rf"\b{re.escape(n)}\b", expression) for n in names)
        if not hit:
            hit = any(
                re.search(rf"\b{re.escape(n)}\b\s*\.\s*c?begin\s*\(", line)
                and not any(
                    re.search(rf"std::{algo}\s*\(\s*{re.escape(n)}\s*\.\s*c?begin\s*\(", line)
                    for algo in SEQUENCE_ONLY)
                for n in names)
        if hit:
            out.append((index + 1, line.strip()))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=pathlib.Path, default=pathlib.Path("."))
    args = ap.parse_args()

    sources: list[pathlib.Path] = []
    for directory in SCOPE:
        base = args.root / directory
        if base.is_dir():
            sources += [p for p in base.rglob("*") if p.suffix in (".cpp", ".h")]

    # A .cpp sees the hashed members declared in its paired header, so names are
    # pooled by stem rather than by file. Pooling them globally instead would
    # flag a std::string called `out` in one file because another file happens
    # to have a hashed set of the same name.
    by_stem: dict[str, set[str]] = {}
    for path in sources:
        by_stem.setdefault(path.stem, set()).update(
            declared_names(path.read_text(errors="replace")))

    findings: list[tuple[pathlib.Path, int, str]] = []
    for path in sorted(sources):
        for line_number, snippet in iteration_sites(path, by_stem.get(path.stem, set())):
            findings.append((path, line_number, snippet))

    if not findings:
        print(f"no unjustified hashed-container iteration in {len(sources)} files")
        return 0

    print(f"Unjustified iteration over a hashed container ({len(findings)}):\n")
    for path, line_number, snippet in findings:
        try:
            shown = path.relative_to(args.root)
        except ValueError:
            shown = path
        print(f"  {shown}:{line_number}\n      {snippet}")
    print(
        f"\nIteration order of std::unordered_* is a property of the standard\n"
        f"library, not of the data. If the order cannot reach emitted text, say\n"
        f"why with a `// {WAIVER}: <reason>` comment on or above the line.\n"
        f"Otherwise use an ordered container.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
